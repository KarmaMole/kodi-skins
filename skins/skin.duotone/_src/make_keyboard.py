"""Generate skins/skin.duotone/1080i/DialogKeyboard.xml (on-screen keyboard).

Id contract copied from reference/skin.estuary-omega/xml/DialogKeyboard.xml:
  311 heading, 312 edit, keys 100-112 / 120-132 / 140-152 / 160-172 (Kodi writes the
  characters), 304 symbols, 303 caps lock, 302 shift, 32 space, 305 left, 306 right,
  8 backspace, side buttons 300 done / 301 cancel / 310 layout / 309 voice-or-IP / 307 IP,
  313 / 314 secondary input labels.
The autocompletion panel 9010 (needs plugin.program.autocompletion) is intentionally omitted.

Layout (Duotone): a bottom slab of the section colour from y 400 under an 8px ink rule; Anton heading,
96px input box with an 8px ink frame and the text in Anton 60, IME candidate lines 313 / 314 (only
for CJK input methods), 13 x 4 key grid (4px rings, Anton 40, solid ink on focus) + function row from
y 640, side blocks (Done / Cancel / layout / voice / IP) in a column at x 1504.

Usage:  python skins/skin.duotone/_src/make_keyboard.py
"""
from pathlib import Path
from default_repeats import strip as strip_defaults  # kodi-review xml.redundant: drop tags that repeat Defaults.xml
from xmlfinish import finish_xml  # kodi-review labels.not-translated: label text goes to strings.po

OUT = Path(__file__).resolve().parent.parent / "1080i" / "DialogKeyboard.xml"

ROWS, COLS = 4, 13
KEY_W, KEY_H, GAP = 84, 72, 8  # keep in sync with constants kb_key_w / kb_key_h
FUNC = [  # id, label, width, columns it maps to (for up/down), type
    (304, "$LOCALIZE[31040]", 176, [0, 1], "radiobutton"),
    (303, "$LOCALIZE[31041]", 84, [2], "radiobutton"),
    (302, "$LOCALIZE[31042]", 84, [3], "radiobutton"),
    (32, "$LOCALIZE[31043]", 360, [4, 5, 6, 7], "button"),
    (305, "◀", 84, [8], "button"),
    (306, "▶", 84, [9], "button"),
    (8, "$LOCALIZE[31044]", 268, [10, 11, 12], "button"),
]
SIDE = [(300, "$LOCALIZE[12321]"), (301, "$LOCALIZE[222]"), (310, ""), (309, ""), (307, "$LOCALIZE[1006]")]


def key_id(r, c):
    return 100 + 20 * r + c


def func_for_col(c):
    for fid, _l, _w, cols, _t in FUNC:
        if c in cols:
            return fid
    raise ValueError(c)


def key_button(r, c, t):
    up = key_id(r - 1, c) if r > 0 else func_for_col(c)
    down = key_id(r + 1, c) if r < ROWS - 1 else func_for_col(c)
    return (f'{t}<control type="button" id="{key_id(r, c)}">\n'
            f'{t}\t<width>kb_key_w</width>\n{t}\t<height>kb_key_h</height>\n'
            f'{t}\t<include>DT_KeyboardKey</include>\n'
            f'{t}\t<onup>{up}</onup>\n{t}\t<ondown>{down}</ondown>\n'
            f'{t}</control>')


def func_button(fid, label, width, cols, ctype, t):
    up = key_id(ROWS - 1, cols[0])
    down = key_id(0, cols[0])
    extra = ""
    if ctype == "radiobutton":
        extra = (f'{t}\t<radiowidth>12</radiowidth>\n{t}\t<radioheight>12</radioheight>\n'
                 f'{t}\t<radioposx>{width - 18}</radioposx>\n{t}\t<radioposy>6</radioposy>\n')
    return (f'{t}<control type="{ctype}" id="{fid}">\n'
            f'{t}\t<width>{width}</width>\n{t}\t<height>kb_key_h</height>\n'
            f'{t}\t<label>{label}</label>\n'
            f'{t}\t<include>DT_KeyboardFunc</include>\n{extra}'
            f'{t}\t<onup>{up}</onup>\n{t}\t<ondown>{down}</ondown>\n'
            f'{t}</control>')


def main():
    t3, t4, t5 = "\t" * 3, "\t" * 4, "\t" * 5
    rows_xml = []
    for r in range(ROWS):
        keys = "\n".join(key_button(r, c, t5) for c in range(COLS))
        rows_xml.append(
            f'{t4}<control type="grouplist">\n{t5}<left>0</left>\n{t5}<top>{r * (KEY_H + GAP)}</top>\n'
            f'{t5}<width>1300</width>\n{t5}<height>kb_key_h</height>\n{t5}<orientation>horizontal</orientation>\n'
            f'{t5}<itemgap>{GAP}</itemgap>\n{t5}<onleft>95200</onleft>\n{t5}<onright>95200</onright>\n'
            f'{keys}\n{t4}</control>')
    funcs = "\n".join(func_button(*f, t5) for f in FUNC)
    rows_xml.append(
        f'{t4}<control type="grouplist">\n{t5}<left>0</left>\n{t5}<top>{ROWS * (KEY_H + GAP)}</top>\n'
        f'{t5}<width>1300</width>\n{t5}<height>kb_key_h</height>\n{t5}<orientation>horizontal</orientation>\n'
        f'{t5}<itemgap>{GAP}</itemgap>\n{t5}<onleft>95200</onleft>\n{t5}<onright>95200</onright>\n'
        f'{funcs}\n{t4}</control>')
    side = "\n".join(
        f'{t4}<include content="DT_DialogButton">\n{t5}<param name="id" value="{sid}"/>\n'
        f'{t5}<param name="label" value="{lab}"/>\n{t5}<param name="width" value="352"/>\n{t5}<param name="height" value="kb_key_h"/>\n{t4}</include>'
        for sid, lab in SIDE)

    xml = f'''<?xml version="1.0" encoding="UTF-8"?>
<!-- GENERATED by _src/make_keyboard.py - edit the generator, not this file.
     On-screen keyboard. Id contract: see the generator docstring (copied from Estuary Omega). -->
<window>
	<defaultcontrol always="true">300</defaultcontrol>
	<include>Anim_DialogOpenClose</include>
	<controls>
		<control type="group">
			<visible>!Window.IsVisible(numericinput)</visible>
			<control type="image">
				<left>-2000</left>
				<top>-2000</top>
				<width>6000</width>
				<height>6000</height>
				<animation effect="fade" start="0" end="100" time="180">WindowOpen</animation>
				<animation effect="fade" start="100" end="0" time="120">WindowClose</animation>
				<texture colordiffuse="$VAR[scrim]">common/white.png</texture>
			</control>
			<control type="image">
				<left>0</left>
				<top>400</top>
				<width>screen_w</width>
				<height>680</height>
				<texture colordiffuse="$VAR[SectionColor]">common/white.png</texture>
			</control>
			<control type="image">
				<left>0</left>
				<top>400</top>
				<width>screen_w</width>
				<height>680</height>
				<aspectratio aligny="top">center</aspectratio>
				<texture colordiffuse="$VAR[dots]">overlays/dots.png</texture>
				<visible>$EXP[DT_Halftone] + $EXP[DT_ScreenDots]</visible>
			</control>
			<control type="image">
				<left>0</left>
				<top>400</top>
				<width>screen_w</width>
				<height>680</height>
				<aspectratio aligny="top">center</aspectratio>
				<texture colordiffuse="$VAR[dots]">overlays/screen_lines.png</texture>
				<visible>$EXP[DT_Halftone] + $EXP[DT_ScreenLines]</visible>
			</control>
			<control type="image">
				<left>0</left>
				<top>400</top>
				<width>screen_w</width>
				<height>680</height>
				<aspectratio aligny="top">center</aspectratio>
				<texture colordiffuse="$VAR[dots]">overlays/screen_coarse.png</texture>
				<visible>$EXP[DT_Halftone] + $EXP[DT_ScreenCoarse]</visible>
			</control>
			<control type="image">
				<left>0</left>
				<top>400</top>
				<width>screen_w</width>
				<height>rule_thick</height>
				<texture colordiffuse="$VAR[ink]">common/white.png</texture>
			</control>
			<control type="label" id="311">
				<left>page_margin</left>
				<top>424</top>
				<width>page_width</width>
				<height>56</height>
				<aligny>center</aligny>
				<font>an_48</font>
				<textcolor>$VAR[SectionText]</textcolor>
			</control>
			<control type="image">
				<left>page_margin</left>
				<top>488</top>
				<width>page_width</width>
				<height>96</height>
				<texture border="16" colordiffuse="$VAR[ink]">common/rect_outline_8.png</texture>
			</control>
			<control type="edit" id="312">
				<left>page_margin</left>
				<top>488</top>
				<width>page_width</width>
				<height>96</height>
				<font>an_60</font>
				<textcolor>$VAR[SectionText]</textcolor>
				<focusedcolor>$VAR[SectionText]</focusedcolor>
				<textoffsetx>28</textoffsetx>
				<aligny>center</aligny>
				<texturefocus />
				<texturenofocus />
			</control>
			<control type="label" id="313">
				<left>page_margin</left>
				<top>590</top>
				<width>page_width</width>
				<height>22</height>
				<font>ui_22</font>
				<textcolor>$VAR[SectionText]</textcolor>
			</control>
			<control type="label" id="314">
				<left>page_margin</left>
				<top>612</top>
				<width>page_width</width>
				<height>22</height>
				<font>ui_22</font>
				<textcolor>$VAR[SectionText]</textcolor>
			</control>
			<control type="group" id="78500">
				<left>page_margin</left>
				<top>640</top>
{chr(10).join(rows_xml)}
			</control>
			<control type="grouplist" id="95200">
				<left>1504</left>
				<top>640</top>
				<width>352</width>
				<height>408</height>
				<orientation>vertical</orientation>
				<itemgap>12</itemgap>
				<onleft>100</onleft>
				<onright>100</onright>
				<onup>95200</onup>
				<ondown>95200</ondown>
{side}
			</control>
		</control>
	</controls>
</window>
'''
    OUT.write_text(finish_xml(strip_defaults(xml, OUT.parent / "Defaults.xml")), encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
