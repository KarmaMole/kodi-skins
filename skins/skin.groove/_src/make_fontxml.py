"""Generate 1080i/Font.xml from one table (docs/skin.groove/DESIGN.md section 3, type scale).

Two fontsets with the same names (Kodi has no glyph fallback): "Default" (Groove faces, built by make_fonts.py)
and "Arial" (Kodi's bundled arial.ttf, for scripts Jost doesn't cover: CJK, Greek extended, ...).
Line pitch of every face = 1.21 em (normalised metrics), so linespacing = CSS line-height / (size x 1.21).
    python skins/skin.groove/_src/make_fontxml.py

Naming (CONVENTIONS.md section 5): font_<role>[_<variant>]. The DESIGN.md roles come first; the engine scale below
them serves the windows forked from Nocturne until M2-M4 move them onto the roles. font13 is Kodi's fallback.
"""
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "1080i" / "Font.xml"

THIN = "Groove-Thin.ttf"
LIGHT = "Groove-Light.ttf"
TEXT = "Groove-Text.ttf"
MED = "Groove-Medium.ttf"
CAPS = "GrooveCaps-Text.ttf"

FONTS = [  # name, file, size, linespacing
    ("font13", TEXT, 26, None),
    # ---- DESIGN.md section 3 roles
    ("font_label", MED, 28, None),         # focused label beside an icon (rail, header title)
    ("font_tray", MED, 24, None),          # label beside a focused tray icon (Now Playing)
    ("font_caption", MED, 30, None),       # one-line caption: title part
    ("font_caption_light", LIGHT, 28, None),  # one-line caption: " · artist · year" part (62 %)
    ("font_np_title", MED, 58, None),      # Now Playing track title
    ("font_hero", MED, 56, None),          # wheel slice name
    ("font_body", TEXT, 26, 1.27),         # liner notes, plots: 26 / 40
    ("font_fact_label", CAPS, 22, None),   # YEAR, LABEL ... (ink2)
    ("font_fact", TEXT, 26, 1.08),         # fact values: 26 / 34
    ("font_small", LIGHT, 24, None),       # times, counts, "+14"
    ("font_small_22", LIGHT, 22, None),    # decade counts
    ("font_clock", LIGHT, 28, None),
    ("font_spine", MED, 21, None),         # spine titles (rotated)
    ("font_numeral", THIN, 440, None),     # Time machine year behind the arc (8 %)
    ("font_name_light", LIGHT, 44, None),  # artist name in place of a missing clearlogo (Now Playing, album info)
    ("font_name_xl", LIGHT, 72, None),     # artist name in place of a missing clearlogo (artist info)
    # ---- engine scale (forked windows; M2-M4 move them onto the roles above)
    ("font_title_xl", MED, 64, 0.9),
    ("font_title_l", MED, 48, 0.92),
    ("font_title", MED, 40, 0.95),
    ("font_title_s", MED, 34, 0.95),
    ("font_lead", LIGHT, 32, 1.0),
    ("font_label_m", MED, 26, None),
    ("font_label_s", MED, 24, None),
    ("font_label_xs", MED, 22, None),
    ("font_body_s", TEXT, 24, 1.24),
    ("font_body_xs", TEXT, 22, 1.2),
    ("font_caps", CAPS, 20, None),
    # ---- Estuary names for third-party script windows. Nothing in Groove uses them, so the official review (kdk
    #      fonts.unused) would list them (each line carries a kdk-ignore, see KDK_ALIAS); they stay: add-on windows (resources/skins/Default) name these fonts and
    #      would fall back to font13 without them. (font_ring / font_ring_22 / font_display went 2026-10-21: unused.)
    ("font10", TEXT, 22, None),
    ("font12", TEXT, 24, None),
    ("font14", TEXT, 28, None),
    ("font27", TEXT, 27, None),
    ("font30", MED, 30, None),
    ("font37", MED, 40, None),
    ("font45", MED, 48, None),
    ("font52_title", MED, 56, None),
    ("font45_title", MED, 48, None),
    ("font36_title", MED, 40, None),
    ("font30_title", MED, 34, None),
    ("font25_title", MED, 30, None),
    ("Mono26", TEXT, 26, None),
]


# Estuary font names kept for third-party script windows (add-on dialogs ask for them by name; Kodi only falls
# back to font13). kdk (the Kodi repository review bot) reports them as unused: each line carries a kdk-ignore.
ESTUARY_ALIASES = {"font10", "font12", "font14", "font27", "font30", "font37", "font45", "font52_title",
                   "font45_title", "font36_title", "font30_title", "font25_title"}
KDK_ALIAS = " <!-- kdk-ignore: fonts; Estuary font name kept for add-on script windows -->"


def font_xml(name, filename, size, ls):
    p = f"<name>{name}</name><filename>{filename}</filename><size>{size}</size>"
    if ls is not None:
        p += f"<linespacing>{ls}</linespacing>"
    return "\t\t<font>" + p + "</font>" + (KDK_ALIAS if name in ESTUARY_ALIASES else "")


def main():
    names = [f[0] for f in FONTS]
    assert len(names) == len(set(names)), "duplicate font name"
    out = ['<?xml version="1.0" encoding="UTF-8"?>',
           "<!-- GENERATED by _src/make_fontxml.py - edit the table there. Licence: fonts/OFL-Jost.txt -->",
           "<fonts>", '\t<fontset id="Default" idloc="31900">']
    out += [font_xml(*f) for f in FONTS]
    out += ["\t</fontset>", '\t<fontset id="Arial" idloc="31901">']
    out += [font_xml(n, "arial.ttf", min(s, 200), l) for n, _f, s, l in FONTS]
    out += ["\t</fontset>", "</fonts>", ""]
    OUT.write_text("\n".join(out), encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({len(FONTS)} fonts)")


if __name__ == "__main__":
    main()
