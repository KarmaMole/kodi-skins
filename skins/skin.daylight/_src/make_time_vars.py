    ranges = {"night": ("22:00", "06:00"), "evening": ("17:00", "22:00"), "afternoon": ("11:00", "17:00"), "morning": ("06:00", "11:00")}
    for mood, (a, b) in ranges.items():
        name = "DL_Is" + mood.capitalize()
        w(f'\t<expression name="{name}">String.IsEqual(Skin.String(daylight.mood),{mood}) | [$EXP[DL_MoodAuto] + System.Time({a},{b})]</expression>')
    w('\t<expression name="DL_IsDark">$EXP[DL_IsNight] | $EXP[DL_IsEvening]</expression>')
    w('\t<expression name="DL_IsLight">!$EXP[DL_IsNight] + !$EXP[DL_IsEvening]</expression>')
    w('\t<variable name="DL_MoodIcon">')
    w('\t\t<value condition="$EXP[DL_IsNight]">daylight/icons/moon.png</value>')
    w('\t\t<value condition="$EXP[DL_IsEvening]">daylight/icons/sunset.png</value>')
    w("\t\t<value>daylight/icons/sun.png</value>")
    w("\t</variable>")
    w('	<variable name="DL_PanelTex">')
    for m in ("n", "e", "a"):
        w(f'		<value condition="$EXP[{MOOD_EXP[m]}]">dialogs/panel_{m}.png</value>')
    w("		<value>dialogs/panel_m.png</value>")
    w("	</variable>")
    for nm, suffix in (("DL_ArtGlowTex", ""), ("DL_ArtGlowTex2", "2")):
        w(f'\t<variable name="{nm}">')
        for m in ("n", "e", "a"):
            w(f'\t\t<value condition="$EXP[{MOOD_EXP[m]}]">daylight/glow_art{suffix}_{m}.png</value>')
        w(f"\t\t<value>daylight/glow_art{suffix}_m.png</value>")
        w("\t</variable>")
    w("\t<!-- ============================================================ colour tokens -->")
    w("\t<!-- One variable per token; values are colour names from colors/defaults.xml (m_/a_/e_/n_). -->")
    for var, suffix in TOKENS.items():
        w(f'\t<variable name="{var}">')
        for m in ("n", "e", "a"):
            w(f'\t\t<value condition="$EXP[{MOOD_EXP[m]}]">{m}_{suffix}</value>')
        w(f"\t\t<value>m_{suffix}</value>")
        w("\t</variable>")
    # TMDb Helper colour normalisation per mood (read by the service on every compute)
    w("\t<!-- TMDb Helper Colors.Main normalisation per mood (Skin.String(TMDbHelper.Colors.Luminance/Saturation)) -->")
    lumsat = {"n": ("0.30", "0.42"), "e": ("0.46", "0.52"), "a": ("0.66", "0.62"), "m": ("0.68", "0.60")}
    for idx, nm in ((0, "DL_ColorLum"), (1, "DL_ColorSat")):
        w(f'\t<variable name="{nm}">')
        for m in ("n", "e", "a"):
            w(f'\t\t<value condition="$EXP[{MOOD_EXP[m]}]">{lumsat[m][idx]}</value>')
        w(f"\t\t<value>{lumsat['m'][idx]}</value>")
        w("\t</variable>")
    w('\t<expression name="DL_ArtColourOn">System.AddonIsEnabled(plugin.video.themoviedb.helper) + !Skin.HasSetting(daylight.noartcolour)</expression>')
    w('\t<expression name="DL_HasArtColour">System.AddonIsEnabled(plugin.video.themoviedb.helper) + !Skin.HasSetting(daylight.noartcolour) + !String.IsEmpty(Window(Home).Property(TMDbHelper.ListItem.Colors.Main))</expression>')

    # ------------------------------------------------------------------ real clock words
    w("\t<!-- ============================================================ real clock (words, rows) -->")
    w('\t<expression name="DL_TimeMorning">System.Time(05:00,12:00)</expression>')
    w('\t<expression name="DL_TimeAfternoon">System.Time(12:00,17:00)</expression>')
    w('\t<expression name="DL_TimeEvening">System.Time(17:00,22:00)</expression>')
    w('\t<expression name="DL_TimeNight">System.Time(22:00,05:00)</expression>')
    w('\t<expression name="DL_PastMidnight">System.Time(00:00,05:00)</expression>')
    w('\t<expression name="DL_Sunday">String.IsEqual(System.Date(DDDD),Sunday)</expression>')
    w('\t<expression name="DL_LongDay">String.IsEqual(System.Date(DDDD),Friday) | String.IsEqual(System.Date(DDDD),Saturday) | String.IsEqual(System.Date(DDDD),Sunday)</expression>')
    w('\t<expression name="DL_Is12h">String.EndsWith(System.Time,M)</expression>')
    w('\t<variable name="DL_DayPart">')
    w('\t\t<value condition="$EXP[DL_PastMidnight]">Past midnight</value>')
    w('\t\t<value condition="$EXP[DL_TimeNight]">$INFO[System.Date(DDDD)] night</value>')
    w('\t\t<value condition="$EXP[DL_TimeEvening]">$INFO[System.Date(DDDD)] evening</value>')
    w('\t\t<value condition="$EXP[DL_TimeAfternoon]">$INFO[System.Date(DDDD)] afternoon</value>')
    w('\t\t<value>$INFO[System.Date(DDDD)] morning</value>')
    w("\t</variable>")

    # ------------------------------------------------------------------ bedtime
    w("\t<!-- ============================================================ bedtime -->")
    for t in BEDTIMES:
        cond = f"String.IsEqual(Skin.String(daylight.bedtime),{t})"
        if t == "00:00":
            cond = f"String.IsEmpty(Skin.String(daylight.bedtime)) | {cond}"
        w(f'\t<expression name="{bed_exp(t)}">{cond}</expression>')
    w('\t<expression name="DL_BedMidnight">String.IsEmpty(Skin.String(daylight.bedtime)) | String.IsEqual(Skin.String(daylight.bedtime),00:00)</expression>')
    w('\t<variable name="DL_BedWord">')
    w('\t\t<value condition="$EXP[DL_BedMidnight]">midnight</value>')
    w("\t\t<value>bedtime</value>")
    w("\t</variable>")
    w('\t<variable name="DL_BedWordYour">')
    w('\t\t<value condition="$EXP[DL_BedMidnight]">midnight</value>')
    w("\t\t<value>your bedtime</value>")
    w("\t</variable>")
    w('\t<variable name="DL_BedtimeLabel">')
    for t in BEDTIMES:
        w(f'\t\t<value condition="$EXP[{bed_exp(t)}] + $EXP[DL_Is12h]">{LABEL12[t]}</value>')
        w(f'\t\t<value condition="$EXP[{bed_exp(t)}]">[B][/B]{t}</value>')
    w("\t</variable>")
    w('\t<variable name="DL_NextBedtime">')
    for i, t in enumerate(BEDTIMES):
        w(f'\t\t<value condition="$EXP[{bed_exp(t)}]">{BEDTIMES[(i + 1) % len(BEDTIMES)]}</value>')
    w("\t</variable>")
    w('\t<variable name="DL_PrevBedtime">')
    for i, t in enumerate(BEDTIMES):
        w(f'\t\t<value condition="$EXP[{bed_exp(t)}]">{BEDTIMES[i - 1]}</value>')
    w("\t</variable>")

    # countdown windows
    on_terms, fits_terms, past_terms, bedtime_now = [], [], [], []
    for t in BEDTIMES:
        b = mins(t)
        on_terms.append(f"[$EXP[{bed_exp(t)}] + {window(b - COUNTDOWN_MAX, b)}]")
        fits_terms.append(f"[$EXP[{bed_exp(t)}] + {window(b - COUNTDOWN_MAX, b - FITS_MIN + 1)}]")
        past_terms.append(f"[$EXP[{bed_exp(t)}] + {window(b, b + 6 * 60)}]")
    w("\t<!-- within 8 h before bedtime / enough left for a film / bedtime passed (up to 6 h ago) -->")
    w(f'\t<expression name="DL_CountdownOn">{" | ".join(on_terms)}</expression>')
    w(f'\t<expression name="DL_FitsOn">{" | ".join(fits_terms)}</expression>')
    w(f'\t<expression name="DL_PastBedtime">{" | ".join(past_terms)}</expression>')

    # hours / minutes left (exact to the minute)
    w("\t<!-- Time left until bedtime: $VAR[DL_LeftH]$VAR[DL_LeftM] = \"2 h 14 min\" -->")
    w('\t<variable name="DL_LeftH">')
    for t in BEDTIMES:
        b = mins(t)
        for k in range(1, COUNTDOWN_MAX // 60 + 1):
            # T in [k*60, k*60+59]  <=>  now in [b-k*60-59, b-k*60]
            w(f'\t\t<value condition="$EXP[{bed_exp(t)}] + {window(b - k * 60 - 59, b - k * 60 + 1)}">{k} h </value>')
    w("\t</variable>")
    w('\t<variable name="DL_LeftM">')
    for bm in (0, 30):
        group = " | ".join(f"$EXP[{bed_exp(t)}]" for t in BEDTIMES if mins(t) % 60 == bm)
        for mm in range(60):
            left = (bm - mm) % 60
            if left == 0:
                continue
            w(f'\t\t<value condition="[{group}] + Integer.IsEqual(System.Time(mm),{mm})">{left} min</value>')
    w("\t</variable>")
    w('\t<variable name="DL_Countdown">')
    w('\t\t<value condition="$EXP[DL_CountdownOn]">$VAR[DL_LeftH]$VAR[DL_LeftM] until $VAR[DL_BedWord]</value>')
    w("\t</variable>")

    # fits threshold (15-minute floor of time left) as xsp hh:mm:ss
    w("\t<!-- Fits-before-bedtime threshold, 15 min floor of the time left (xsp value hh:mm:ss) -->")
    w('\t<variable name="DL_FitsMax">')
    for t in BEDTIMES:
        b = mins(t)
        for q in range(FITS_MIN // 15, COUNTDOWN_MAX // 15 + 1):
            lo = q * 15
            # T in [lo, lo+14] <=> now in [b-lo-14, b-lo]
            val = f"{lo // 60:02d}:{lo % 60:02d}:00"
            w(f'\t\t<value condition="$EXP[{bed_exp(t)}] + {window(b - lo - 14, b - lo + 1)}">{val}</value>')
    w("\t</variable>")

    # minutes left (15 min floor) as "135 min": set into Window(Home).Property(daylight.leftmins) on window
    # load so Integer.IsLessOrEqual(ListItem.Duration(mins),Window(Home).Property(daylight.leftmins)) works
    w('	<variable name="DL_LeftMinsQ">')
    for t in BEDTIMES:
        b = mins(t)
        for q in range(0, COUNTDOWN_MAX // 15 + 1):
            lo = q * 15
            w(f'		<value condition="$EXP[{bed_exp(t)}] + {window(b - lo - 14, b - lo + 1)}">{lo} min</value>')
    w("		<value>0 min</value>")
    w("	</variable>")
    w('	<expression name="DL_ItemFits">$EXP[DL_CountdownOn] + Integer.IsGreater(ListItem.Duration(mins),0) + Integer.IsLessOrEqual(ListItem.Duration(mins),Window(Home).Property(daylight.leftmins))</expression>')

    # ------------------------------------------------------------------ greeting
    w("\t<!-- ============================================================ greeting + subline -->")
    w('\t<variable name="DL_Greeting">')
    w('\t\t<value condition="$EXP[DL_PastBedtime] | $EXP[DL_PastMidnight]">Still up?</value>')
    w('\t\t<value condition="$EXP[DL_TimeNight]">Nearly bedtime.</value>')
    w('\t\t<value condition="$EXP[DL_TimeEvening]">Good evening.</value>')
    w('\t\t<value condition="$EXP[DL_TimeAfternoon]">Good afternoon.</value>')
    w("\t\t<value>Good morning.</value>")
    w("\t</variable>")
    w('\t<variable name="DL_Subline">')
    w('\t\t<value condition="$EXP[DL_CountdownOn]">$VAR[DL_Countdown]</value>')
    w('\t\t<value condition="$EXP[DL_PastBedtime] | $EXP[DL_TimeNight]">Short ones: under 100 minutes</value>')
    w('\t\t<value condition="$EXP[DL_TimeEvening]">The evening is yours</value>')
    w('\t\t<value condition="$EXP[DL_TimeAfternoon] + $EXP[DL_LongDay]">A free afternoon: something long</value>')
    w('\t\t<value condition="$EXP[DL_TimeAfternoon]">Plenty of daylight left</value>')
    w('\t\t<value condition="$EXP[DL_Sunday]">Sunday morning: take it slow</value>')
    w("\t\t<value>A slow start: something light</value>")
    w("\t</variable>")

    # ------------------------------------------------------------------ weather
    w("\t<!-- ============================================================ weather (weather.gismeteo) -->")
    w('\t<expression name="DL_HasWeather">Weather.IsFetched + !String.IsEmpty(Weather.Conditions) + !String.IsEqual(Weather.Conditions,Busy)</expression>')
    rain = " | ".join(f"Integer.IsEqual(Weather.FanartCode,{c})" for c in RAIN_CODES)
    snow = " | ".join(f"Integer.IsEqual(Weather.FanartCode,{c})" for c in SNOW_CODES)
    w(f'\t<expression name="DL_Rain">$EXP[DL_HasWeather] + [{rain} | String.Contains(Weather.Conditions,ain) | String.Contains(Weather.Conditions,hower) | String.Contains(Weather.Conditions,rizzle) | String.Contains(Weather.Conditions,hunder)]</expression>')
    w(f'\t<expression name="DL_Snow">$EXP[DL_HasWeather] + [{snow} | String.Contains(Weather.Conditions,now) | String.Contains(Weather.Conditions,leet)]</expression>')
    w('\t<expression name="DL_WeatherRow">!Skin.HasSetting(daylight.noweather) + [$EXP[DL_Rain] | $EXP[DL_Snow]]</expression>')
    w('\t<expression name="DL_RainOverlay">!Skin.HasSetting(daylight.noweather) + !Skin.HasSetting(daylight.reducemotion) + $EXP[DL_Rain]</expression>')
    # Words and icons come from Weather.FanartCode (Kodi's 0-47 code set): weather.gismeteo returns
    # condition text with a Cyrillic first letter on Omar's box (U+0421 "Clear"), which Figtree can't draw.
    words = {0: "tornado", 1: "tropical storm", 2: "hurricane", 3: "severe storms", 4: "thunderstorms", 5: "rain and snow",
             6: "rain and sleet", 7: "snow and sleet", 8: "freezing drizzle", 9: "drizzle", 10: "freezing rain", 11: "showers",
             12: "showers", 13: "snow flurries", 14: "light snow", 15: "blowing snow", 16: "snow", 17: "hail", 18: "sleet",
             19: "dust", 20: "fog", 21: "haze", 22: "smoke", 23: "blustery", 24: "windy", 25: "cold", 26: "cloudy",
             27: "mostly cloudy", 28: "mostly cloudy", 29: "partly cloudy", 30: "partly cloudy", 31: "clear", 32: "sunny",
             33: "fair", 34: "fair", 35: "rain and hail", 36: "hot", 37: "isolated storms", 38: "scattered storms",
             39: "scattered storms", 40: "scattered showers", 41: "heavy snow", 42: "snow showers", 43: "heavy snow",
             44: "partly cloudy", 45: "thundershowers", 46: "snow showers", 47: "isolated storms"}
    w('\t<variable name="DL_WeatherWord">')
    for code, word in words.items():
        w(f'\t\t<value condition="String.IsEqual(Weather.FanartCode,{code})">{word}</value>')
