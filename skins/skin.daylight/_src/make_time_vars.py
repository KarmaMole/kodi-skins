"""Generate 1080i/Includes_Daylight.xml: Daylight's time engine (moods, colour tokens, greeting,
countdown, contextual rows, bedtime maths). Kodi has no arithmetic, so every clock-derived value is
a lookup table of System.Time(start,end) windows / Integer.IsEqual buckets, written out here.

Verified engine facts (Kodi 21 Omega source, 2026-10-18):
  * System.Time(HH:mm,HH:mm) is minute-of-day based (24 h, region independent), start inclusive,
    end exclusive, and wraps past midnight when end < start (SystemGUIInfo.cpp).
  * System.Time(hh)/(hh:mm) LABELS follow the region clock (Omar's box: 12 h, "12:23 PM"), so labels
    are never parsed for hours; Player.FinishTime(hh) is used mod 12 (works for 12 h and 24 h).
  * $VAR works in colour attributes/tags, [COLOR ...], texture paths and <content> paths; the
    directory provider reloads when the evaluated path changes.
  * xsp time rules take "hh:mm:ss" (StringUtils::TimeStringToSeconds).

Usage: python skins/skin.daylight/_src/make_time_vars.py
"""
import re
from pathlib import Path
import json
import urllib.parse

OUT = Path(__file__).resolve().parents[1] / "1080i" / "Includes_Daylight.xml"

MOODS = ("n", "e", "a", "m")  # evaluation order: night, evening, afternoon, default morning
MOOD_EXP = {"n": "DL_IsNight", "e": "DL_IsEvening", "a": "DL_IsAfternoon"}
TOKENS = {
    # variable: colour suffix in colors/defaults.xml
    "DL_Ground": "ground", "DL_Surface": "surface", "DL_Raised": "raised",
    "DL_Ink": "ink", "DL_Body": "body", "DL_Ink2": "ink2", "DL_Ink3": "ink3", "DL_Disabled": "disabled",
    "DL_Line": "line", "DL_Line2": "line2", "DL_Accent": "accent", "DL_AccentText": "accenttext",
    "DL_OnAccent": "onaccent", "DL_Scrim": "ground", "DL_ScrimTrack": "scrimtrack", "DL_DimDialog": "dimdialog",
    "DL_Shadow": "shadow", "DL_Halo": "halo", "DL_GlowA": "glowa", "DL_GlowB": "glowb",
    "DL_ArtDim": "artdim", "DL_DimArt2": "artdim",
    "DL_FloorShade": "floor", "DL_RainTint": "rain", "DL_Chip": "chip", "DL_ChipText": "chiptext", "DL_Panel": "panel",
}

BEDTIMES = ["21:00", "21:30", "22:00", "22:30", "23:00", "23:30", "00:00", "00:30", "01:00", "01:30", "02:00"]
LABEL12 = {"21:00": "9:00 PM", "21:30": "9:30 PM", "22:00": "10:00 PM", "22:30": "10:30 PM", "23:00": "11:00 PM",
           "23:30": "11:30 PM", "00:00": "12:00 AM", "00:30": "12:30 AM", "01:00": "1:00 AM", "01:30": "1:30 AM",
           "02:00": "2:00 AM"}
COUNTDOWN_MAX = 8 * 60      # countdown + "fits" row shown within 8 h of bedtime
FITS_MIN = 45               # below 45 min left nothing sensible fits

RAIN_CODES = [1, 2, 3, 4, 6, 8, 9, 10, 11, 12, 17, 18, 35, 37, 38, 39, 40, 45, 47]
SNOW_CODES = [5, 7, 13, 14, 15, 16, 41, 42, 43, 46]


def hm(minutes: int) -> str:
    minutes %= 1440
    return f"{minutes // 60:02d}:{minutes % 60:02d}"


def mins(t: str) -> int:
    h, m = t.split(":")
    return int(h) * 60 + int(m)


def bed_exp(t: str) -> str:
    return "DL_Bed" + t.replace(":", "")


def window(start: int, end: int) -> str:
    """System.Time window [start, end) in minutes (wraps)."""
    return f"System.Time({hm(start)},{hm(end)})"


def esc(s: str) -> str:
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def xsp(rules, method, direction="descending", kind="movies"):
    body = {"rules": {"and": rules}, "type": kind, "order": {"method": method, "direction": direction, "ignorefolders": 0}}
    q = urllib.parse.quote(json.dumps(body, separators=(",", ":")), safe="")
    return f"videodb://{kind}/titles/?xsp={q}"


UNWATCHED = {"field": "playcount", "operator": "is", "value": "0"}


def under(t):  # runtime strictly under t (hh:mm:ss)
    return {"field": "time", "operator": "lessthan", "value": t}


# 0.9.3: films with no runtime in the library (0) passed every "under" rule and were offered as
# "fits before bedtime"; every under() rule list also carries this one.
HAS_RUNTIME = {"field": "time", "operator": "greaterthan", "value": "00:00:00"}


def over(t):
    return {"field": "time", "operator": "greaterthan", "value": t}


def main() -> None:
    L = []
    w = L.append
    w('<?xml version="1.0" encoding="UTF-8"?>')
    w("<!-- GENERATED by _src/make_time_vars.py - edit the generator, not this file. -->")
    w("<!--")
    w("\tDaylight time engine: moods + colour tokens, greeting, countdown to bedtime, contextual Home rows,")
    w("\tweather, OSD bedtime maths. Settings: daylight.mood (empty/auto, morning, afternoon, evening, night),")
    w("\tdaylight.bedtime (HH:mm from the list below, empty = 00:00 midnight), daylight.noweather,")
    w("\tdaylight.noartcolour. Palette follows the mood setting; words and rows follow the real clock.")
