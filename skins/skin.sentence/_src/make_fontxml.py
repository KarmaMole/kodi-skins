"""Generate skins/skin.sentence/1080i/Font.xml from one table (docs/skin.sentence/DESIGN.md section 3).

Two fontsets with identical names (Kodi has no per-glyph fallback):
  * "Default" - Young Serif (sentences, titles) + Manrope (UI) + the derived Sentence Caps / Num
  * "Arial"   - Kodi's bundled arial.ttf at the same sizes (Settings > Interface > Skin > Fonts),
                for titles in scripts Young Serif / Manrope don't cover.
linespacing = mockup CSS line-height / natural line height (Young Serif 1.412 em, Manrope 1.366 em).

Usage:  python skins/skin.sentence/_src/make_fontxml.py
"""
