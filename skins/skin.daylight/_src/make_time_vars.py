    for c in (31, 33):
        icon_of[c] = "moon"
    for c in (32, 34, 36):
        icon_of[c] = "sun"
    w('\t<variable name="DL_WeatherIcon">')
    for kind in ("rain", "snow", "moon", "sun"):
        cond = " | ".join(f"String.IsEqual(Weather.FanartCode,{c})" for c, k in icon_of.items() if k == kind)
        w(f'\t\t<value condition="{cond}">daylight/icons/{kind}.png</value>')
    w("\t\t<value>daylight/icons/cloud.png</value>")
    w("\t</variable>")
    # the same words / icons for forecast list items (Misc_WeatherDay puts DayN.FanartCode in Property(Code))
    w('\t<variable name="DL_WeatherWordItem">')
    for code, word in words.items():
        w(f'\t\t<value condition="String.IsEqual(ListItem.Property(Code),{code})">{word[:1].upper() + word[1:]}</value>')
    w('\t\t<value>$INFO[ListItem.Property(Outlook)]</value>')
    w("\t</variable>")
    w('\t<variable name="DL_WeatherIconItem">')
    for kind in ("rain", "snow", "moon", "sun"):
        cond = " | ".join(f"String.IsEqual(ListItem.Property(Code),{c})" for c, k in icon_of.items() if k == kind)
        w(f'\t\t<value condition="{cond}">daylight/icons/{kind}.png</value>')
    w("\t\t<value>daylight/icons/cloud.png</value>")
    w("\t</variable>")
    w('\t<variable name="DL_WeatherWordCap">')
    for code, word in words.items():
        w(f'\t\t<value condition="String.IsEqual(Weather.FanartCode,{code})">{word[:1].upper() + word[1:]}</value>')
    w('\t\t<value>$INFO[Weather.Conditions]</value>')
    w("\t</variable>")
    w('\t<variable name="DL_WeatherShort">')
    w('\t\t<value condition="$EXP[DL_HasWeather]">$INFO[Weather.Temperature]</value>')
    w("\t</variable>")
    w('\t<variable name="DL_WeatherLong">')
    w('\t\t<value condition="$EXP[DL_HasWeather]">$INFO[Weather.Temperature] $VAR[DL_WeatherWord]</value>')
    w("\t</variable>")

    # ------------------------------------------------------------------ contextual rows
    w("\t<!-- ============================================================ contextual rows (Home) -->")
    p_docs = xsp([UNWATCHED, {"field": "genre", "operator": "contains", "value": "Documentary"}], "random")
    p_short = xsp([UNWATCHED, HAS_RUNTIME, under("01:40:00")], "rating")
    p_short_rand = xsp([UNWATCHED, HAS_RUNTIME, under("01:40:00")], "random")
    p_long = xsp([UNWATCHED, over("02:20:00")], "rating")
    p_long_rand = xsp([UNWATCHED, over("02:20:00"), {"field": "rating", "operator": "greaterthan", "value": "6.5"}], "random")
    p_rain = xsp([UNWATCHED, over("02:30:00")], "rating")
    p_rain_night = xsp([UNWATCHED, HAS_RUNTIME, under("01:00:00")], "rating")
    p_top = xsp([UNWATCHED, {"field": "rating", "operator": "greaterthan", "value": "7"}], "rating")
    p_top_rand = xsp([UNWATCHED, {"field": "rating", "operator": "greaterthan", "value": "7"}], "random")
    p_light = xsp([UNWATCHED, HAS_RUNTIME, under("02:00:00"), {"field": "genre", "operator": "contains", "value": ["Comedy", "Animation", "Family", "Documentary"]}], "random")
    p_added = "videodb://recentlyaddedmovies/"
    # fits: threshold injected from DL_FitsMax ($VAR inside the encoded JSON value)
    fits_tpl = xsp([UNWATCHED, HAS_RUNTIME, under("@@FITS@@")], "rating").replace("%40%40FITS%40%40", "$VAR[DL_FitsMax]")
