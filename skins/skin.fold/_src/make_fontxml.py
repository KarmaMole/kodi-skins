"""Generate skins/skin.fold/1080i/Font.xml from one table (docs/skin.fold/DESIGN.md, type scale).

Two fontsets with the same names: "Default" (Fold derivatives from make_fonts.py) and "Arial" (Kodi's
bundled arial.ttf, for scripts Bricolage / Plex Mono don't cover).
Natural line pitch: Bricolage derivatives 1.20 em, Plex Mono derivatives 1.30 em, so
linespacing = CSS line-height / (pitch x size).

    python skins/skin.fold/_src/make_fontxml.py
"""
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE.parent / "1080i" / "Font.xml"

DISP = "FoldDisplay-ExtraBold.ttf"
HEAD = "FoldHead-Bold.ttf"
LIGHT = "FoldText-Light.ttf"
REG = "FoldText-Regular.ttf"
SEMI = "FoldText-SemiBold.ttf"
TAB = "FoldTab-SemiBold.ttf"
WORD = "FoldWord-ExtraBold.ttf"
CAPS = "FoldCaps-Regular.ttf"
CAPSB = "FoldCaps-SemiBold.ttf"
META = "FoldMeta-Regular.ttf"
NUM = "FoldNum-Medium.ttf"
NUMR = "FoldNum-Regular.ttf"
MONO_FILES = {CAPS, CAPSB, META, NUM, NUMR}


def ls(file, line_height, size):
    pitch = 1.3 if file in MONO_FILES else 1.2
    return round(line_height / (pitch * size), 3)


# name, file, size, CSS line-height px (None = natural)
