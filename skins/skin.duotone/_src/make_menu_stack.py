"""Custom main-menu items in Duotone's section stack (list 300), 0.9.17 (docs/CUSTOM_MENU_BRIEF_2026-10-28.md).

Order in list 300: Films, Series, Music (each can hide, HideMenu.*), custom items 1-3 (CustomMenu<n>On, the
generated static items CustomMenu_ListItem from tools/customrows/make_customrows.py), Search (never hides).
Everything keyed on list 300's POSITION is written here, so the combinations stay consistent:

  * Includes_Home.xml: DT_MenuShown0-3 (how many of Films / Series / Music show), Home_SecSearch (Search's position
    now also counts the custom items: CustomMenuCount0-3), Home_SecCustom (a custom item has focus), the item
    layouts of list 300 and the name probes.
  * Expressions.xml: DT_HomeSearch / DT_HomeCustom (window-wide section tests; dialogs fall back on
    Window(Home).Property(duotone.section)).
  * Home.xml: the onloads that reselect the remembered section at its new position while anything is hidden or a
    custom item shows (a static list keeps its INDEX when items come and go, LESSONS "Main menu items").

The stack has to stay inside its 740 px column: with more than 4 items the unfocused words get a smaller Anton
(conditional item layouts on Container(300).NumItems; 4 or fewer = the release layout, unchanged). A custom item's
name is fitted to the 696 px column with probe textboxes (Kodi 21 has no String.Length; NumPages > 1 = it needs a
second line at that size, the same trick as _src/make_titles.py), one set per slot, outside the list.

Usage: python skins/skin.duotone/_src/make_menu_stack.py     (re-run after changing anything below)
"""
import re
from pathlib import Path

X = Path(__file__).resolve().parents[1] / "1080i"
HIDE = {"films": "Skin.HasSetting(HideMenu.Movies)", "series": "Skin.HasSetting(HideMenu.TVShows)",
        "music": "Skin.HasSetting(HideMenu.Music)"}
B = ("films", "series", "music")
CI = "Container(300).CurrentItem"
SEC = "Window(Home).Property(duotone.section)"
NUM = "Container(300).NumItems"

# unfocused layout per item count: (condition, row height, Anton size, label top, count top)
UNFOCUSED = [
    (f"!Integer.IsGreater({NUM},4)", 158, 176, -19, 128),     # the release layout (4 or fewer items)
    (f"Integer.IsEqual({NUM},5)", 132, 136, -15, 102),       # 4 x 132 + 212 = 740
    (f"Integer.IsEqual({NUM},6)", 105, 104, -11, 75),        # 5 x 105 + 212 = 737
    (f"Integer.IsGreater({NUM},6)", 88, 88, -9, 58),         # 6 x 88 + 212 = 740
]
FOCUSED = (212, 236, -25, 183)
TIERS = [236, 200, 176, 150, 136, 104, 88, 72]   # name sizes for a custom item, largest first


def name_top(size):
    # Anton in a centred label: the caps sit 0.107 x size above the box centre (-19 at 176, -25 at 236)
    return round(-0.107 * size)


def pid(slot, size):
    return 7300 + 10 * slot + TIERS.index(size)


def fits(slot, size):
    return f"!Integer.IsGreater(Container({pid(slot, size)}).NumPages,1)"


def pitch(size):
    return size * 1.505 * (0.63 if size == 72 else 0.585)


def combos(names):
    out = [[]]
    for n in names:
        out = [c + [(n, v)] for c in out for v in (True, False)]
    return out


def shown_count_terms(k):
    terms = []
    for c in combos(B):
        if sum(v for _, v in c) == k:
            terms.append("[" + " + ".join(("!" if v else "") + HIDE[n] for n, v in c) + "]")
    return " | ".join(terms)


def pos_test(p, empty_ok):
    """list 300's 1-based position == p (empty_ok: an empty CurrentItem counts as the first item, as at load)"""
    if p == 1 and empty_ok:
        return f"!Integer.IsGreater({CI},1)"
    return f"Integer.IsEqual({CI},{p})"


def range_test(lo, hi, empty_ok):
    if lo == 1 and empty_ok:
        return f"!Integer.IsGreater({CI},{hi})"
    return f"Integer.IsGreater({CI},{lo - 1}) + Integer.IsLess({CI},{hi + 1})"


def search_terms(empty_ok):
    return " | ".join(f"[$EXP[DT_MenuShown{nb}] + $EXP[CustomMenuCount{nc}] + {pos_test(nb + nc + 1, empty_ok)}]"
                      for nb in range(4) for nc in range(4))


def custom_terms(empty_ok):
    return " | ".join(f"[$EXP[DT_MenuShown{nb}] + $EXP[CustomMenuCount{nc}] + {range_test(nb + 1, nb + nc, empty_ok)}]"
                      for nb in range(4) for nc in range(1, 4))


def home_expressions():
    out = ["\t<!-- BEGIN menu positions: GENERATED by _src/make_menu_stack.py (edit the generator) -->"]
    for k in range(4):
        out.append(f'\t<expression name="DT_MenuShown{k}">{shown_count_terms(k)}</expression>')
    out.append(f'\t<expression name="Home_SecSearch">{search_terms(True)}</expression>')
    out.append(f'\t<expression name="Home_SecCustom">{custom_terms(True)}</expression>')
    out.append("\t<!-- END menu positions -->")
    return "\n".join(out)


def window_expressions():
    out = ["\t<!-- BEGIN menu positions: GENERATED by _src/make_menu_stack.py (edit the generator) -->"]
    out.append(f'\t<expression name="DT_HomeSearch">Window.IsActive(home) + [{search_terms(False)} | '
               f'[String.IsEmpty({CI}) + String.IsEqual({SEC},search)]]</expression>')
    out.append(f'\t<expression name="DT_HomeCustom">Window.IsActive(home) + [{custom_terms(False)} | '
               f'[String.IsEmpty({CI}) + String.StartsWith({SEC},custom)]]</expression>')
    out.append("\t<!-- END menu positions -->")
    return "\n".join(out)


def row_controls(t, h, size, top, count_top, color):
    is_builtin = "String.IsEmpty(ListItem.Property(custommenu))"
    out = [f"{t}<control type=\"label\">", f"{t}\t<left>0</left>", f"{t}\t<top>{top}</top>", f"{t}\t<width>696</width>",
           f"{t}\t<height>{h}</height>", f"{t}\t<aligny>center</aligny>", f"{t}\t<font>an_{size}</font>",
           f"{t}\t<textcolor>{color}</textcolor>", f"{t}\t<label>$INFO[ListItem.Label]</label>",
           f"{t}\t<visible>{is_builtin}</visible>", f"{t}</control>"]
    # a custom item's name: the largest size up to the row's own that fits the column on one line
    cands = [s for s in TIERS if s <= size]
    for i, s in enumerate(cands):
        conds = []
        for slot in (1, 2, 3):
            c = [f"String.IsEqual(ListItem.Property(custommenu),{slot})"]
            if i < len(cands) - 1:
                c.append(fits(slot, s))
            if i > 0:
                c.append(f"Integer.IsGreater(Container({pid(slot, cands[i - 1])}).NumPages,1)")  # not the size above
            conds.append("[" + " + ".join(c) + "]")
        out += [f"{t}<control type=\"label\">", f"{t}\t<left>0</left>", f"{t}\t<top>{top - name_top(size) + name_top(s)}</top>",
                f"{t}\t<width>696</width>", f"{t}\t<height>{h}</height>", f"{t}\t<aligny>center</aligny>",
                f"{t}\t<font>an_{s}</font>", f"{t}\t<textcolor>{color}</textcolor>",
                f"{t}\t<label>$INFO[ListItem.Label]</label>", f"{t}\t<visible>{' | '.join(conds)}</visible>", f"{t}</control>"]
    out += [f"{t}<control type=\"label\">", f"{t}\t<right>0</right>", f"{t}\t<top>{count_top}</top>", f"{t}\t<width>200</width>",
            f"{t}\t<height>28</height>", f"{t}\t<align>right</align>", f"{t}\t<aligny>top</aligny>",
            f"{t}\t<font>cap_24</font>", f"{t}\t<textcolor>{color}</textcolor>",
            f"{t}\t<label>$INFO[ListItem.Label2]</label>", f"{t}</control>"]
    return out


def layouts():
    t = "\t\t\t"
    out = [f"{t}<!-- BEGIN stack layouts: GENERATED by _src/make_menu_stack.py (edit the generator) -->"]
    for cond, h, size, top, count_top in UNFOCUSED:
        out.append(f'{t}<itemlayout width="696" height="{h}" condition="{cond}">')
        out += row_controls(t + "\t", h, size, top, count_top, "$VAR[SectionFaint]")
        out.append(f"{t}</itemlayout>")
    h, size, top, count_top = FOCUSED
    out.append(f'{t}<focusedlayout width="696" height="{h}">')
    out += row_controls(t + "\t", h, size, top, count_top, "$VAR[SectionText]")
    out.append(f"{t}</focusedlayout>")
    out.append(f"{t}<!-- END stack layouts -->")
    return "\n".join(out)


def probes():
    out = ["\t<!-- BEGIN name probes: GENERATED by _src/make_menu_stack.py. One clear textbox per slot and size: NumPages > 1"
           "\n\t     = the name needs two lines at that size in the 696 px stack column -->",
           '\t<include name="Home_CustomMenuProbes">', "\t\t<control type=\"group\">",
           "\t\t\t<left>page_margin</left>", "\t\t\t<top>182</top>", "\t\t\t<width>696</width>"]
    for slot in (1, 2, 3):
        for s in TIERS[:-1]:
            out += ["\t\t\t<control type=\"textbox\" id=\"%d\">" % pid(slot, s), "\t\t\t\t<left>0</left>", "\t\t\t\t<top>0</top>",
                    "\t\t\t\t<width>696</width>", f"\t\t\t\t<height>{round(pitch(s) * 1.5)}</height>",
                    f"\t\t\t\t<font>an_{s}</font>", "\t\t\t\t<textcolor>clear</textcolor>",
                    f"\t\t\t\t<label>$VAR[CustomMenu_Label{slot}]</label>",
                    f"\t\t\t\t<visible>$EXP[CustomMenu{slot}On]</visible>", "\t\t\t</control>"]
    out += ["\t\t</control>", "\t</include>", "\t<!-- END name probes -->"]
    return "\n".join(out)


def onloads():
    gate = ("[" + " | ".join(HIDE[b] for b in B) + " | " +
            " | ".join(f"$EXP[CustomMenu{k}On]" for k in (1, 2, 3)) + "]")
    out = ["\t<!-- BEGIN reselect: GENERATED by _src/make_menu_stack.py. Sections can be hidden (HideMenu.*) and custom",
           "\t     items come and go, which shifts the positions in list 300: while anything is hidden or a custom item",
           "\t     shows, select the remembered section at its new position (0-based), or the first one when it is gone -->"]

    def line(sec, conds, p):
        c = " + ".join([f"String.IsEqual({SEC},{sec})", gate] + conds)
        out.append(f'\t<onload condition="{c}">SetFocus(300,{p},absolute)</onload>')

    for i, s in enumerate(B):
        for c in combos(B[:i]):
            line(s, [("!" if v else "") + HIDE[n] for n, v in c] + ["!" + HIDE[s]], sum(v for _, v in c))
        line(s, [HIDE[s]], 0)
    for k in (1, 2, 3):
        earlier = [f"CustomMenu{j}On" for j in range(1, k)]
        for nb in range(4):
            for c in combos(earlier):
                line(f"custom{k}", [f"$EXP[DT_MenuShown{nb}]"] + [("" if v else "!") + f"$EXP[{n}]" for n, v in c] +
                     [f"$EXP[CustomMenu{k}On]"], nb + sum(v for _, v in c))
        line(f"custom{k}", [f"!$EXP[CustomMenu{k}On]"], 0)
    for nb in range(4):
        for nc in range(4):
            line("search", [f"$EXP[DT_MenuShown{nb}]", f"$EXP[CustomMenuCount{nc}]"], nb + nc)
    out.append("\t<!-- END reselect -->")
    return "\n".join(out)


def put(path, begin, end, block, fallback_pattern=None):
    t = path.read_text(encoding="utf-8")
    if begin in t:
        i = t.index(begin)
        i = t.rindex("\n", 0, i) + 1
        j = t.index(end, i)
        j = t.index("\n", j) + 1
        t = t[:i] + block + "\n" + t[j:]
    else:
        m = re.search(fallback_pattern, t, re.S)
        assert m, (path, fallback_pattern)
        t = t[:m.start()] + block + "\n" + t[m.end():]
    path.write_text(t, encoding="utf-8", newline="\n")


def main():
    ih = X / "Includes_Home.xml"
    put(ih, "BEGIN menu positions", "END menu positions", home_expressions(),
        r'\t<expression name="Home_SecSearch">[^\n]*</expression>\n')
    put(ih, "BEGIN stack layouts", "END stack layouts", layouts(),
        r'\t\t\t<itemlayout width="696" height="158">.*?</focusedlayout>\n')
    put(ih, "BEGIN name probes", "END name probes", probes(), r"\t<!-- MENU PROBES -->\n")
    put(X / "Expressions.xml", "BEGIN menu positions", "END menu positions", window_expressions(),
        r'\t<expression name="DT_HomeSearch">[^\n]*</expression>\n')
    put(X / "Home.xml", "BEGIN reselect", "END reselect", onloads(),
        r"\t<!-- 0\.9\.13: sections can be hidden.*?(?=\t<onload>SetProperty\(duotone\.reload)")
    print("wrote Includes_Home.xml, Expressions.xml, Home.xml")


if __name__ == "__main__":
    main()
