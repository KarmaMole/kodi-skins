"""Generate 1080i/Includes_Paths.xml: the smart-playlist content paths behind today's page and the unwatched.

Kodi smart-playlist rules inlined into library URLs (videodb://...?xsp=<url-encoded json>). The relative date
operators are real Kodi operators (verified with Files.GetDirectory on the Shield, 2026-10-19):
    a year ago this week   lastplayed inthelast 372 days AND notinthelast 358 days   (watched 51-53 weeks ago)
    a year ago this month  inthelast 395 days AND notinthelast 335 days
    two years ago          inthelast 760 days AND notinthelast 700 days
    this year              lastplayed startswith $INFO[System.Date(yyyy)]
    waiting                playcount is 0 AND inprogress false; per year: dateadded startswith <year>
The xsp "order" is ignored by library nodes (LESSONS round 3): order with the container's sortby/sortorder.
$INFO[...] is inserted after url-encoding, so Kodi resolves it when it builds the path.

Usage: python skins/skin.keepsake/_src/make_paths.py
"""
from __future__ import annotations

import json
import urllib.parse
from pathlib import Path
from xmlfinish import finish_xml  # kodi-review labels.not-translated: label text goes to strings.po

OUT = Path(__file__).resolve().parents[1] / "1080i" / "Includes_Paths.xml"
YEAR = "@@YEAR@@"
DAY = "@@DAY@@"
MOVIES = "videodb://movies/titles/"
EPISODES = "videodb://tvshows/titles/-1/-1/"
SHOWS = "videodb://tvshows/titles/"
UNW_YEARS = range(2000, 2036)


def rule(field, op, value=""):
    return {"field": field, "operator": op, "value": [value]}


def xsp(base, typ, *rules):
    j = json.dumps({"rules": {"and": list(rules)}, "type": typ}, separators=(",", ":"))
    enc = urllib.parse.quote(j, safe="")
    enc = enc.replace(urllib.parse.quote(YEAR, safe=""), "$INFO[System.Date(yyyy)]")
    enc = enc.replace(urllib.parse.quote(DAY, safe=""), "$VAR[KS_UF_YM]$VAR[KS_UF_PD]")
    return base + "?xsp=" + enc


PATHS = {
    "YAWeek": xsp(MOVIES, "movies", rule("lastplayed", "inthelast", "372 days"), rule("lastplayed", "notinthelast", "358 days")),
    "YAMonth": xsp(MOVIES, "movies", rule("lastplayed", "inthelast", "395 days"), rule("lastplayed", "notinthelast", "335 days")),
    "YA2": xsp(MOVIES, "movies", rule("lastplayed", "inthelast", "760 days"), rule("lastplayed", "notinthelast", "700 days")),
    "Watched": xsp(MOVIES, "movies", rule("playcount", "greaterthan", "0")),
    "Stopped": xsp(MOVIES, "movies", rule("inprogress", "true"), rule("lastplayed", "notinthelast", "14 days")),
    "FilmsRecent": xsp(MOVIES, "movies", rule("inprogress", "true"), rule("lastplayed", "inthelast", "14 days")),
    "EpInProgress": xsp(EPISODES, "episodes", rule("inprogress", "true")),
    "FilmsThisYear": xsp(MOVIES, "movies", rule("playcount", "greaterthan", "0"), rule("lastplayed", "startswith", YEAR)),
    "SeriesThisYear": xsp(SHOWS, "tvshows", rule("lastplayed", "startswith", YEAR)),
    "Waiting": xsp(MOVIES, "movies", rule("playcount", "is", "0"), rule("inprogress", "false")),
    # the brief's mechanic: never played and added five years ago or more
    "WaitingFive": xsp(MOVIES, "movies", rule("playcount", "is", "0"), rule("inprogress", "false"),
                       rule("dateadded", "notinthelast", "1825 days")),
    # never-played films added on the same day as the focused print (unwatched page side note)
    "SameDay": xsp(MOVIES, "movies", rule("playcount", "is", "0"), rule("inprogress", "false"), rule("dateadded", "startswith", DAY)),
}
for y in UNW_YEARS:
    PATHS[f"Waiting{y}"] = xsp(MOVIES, "movies", rule("playcount", "is", "0"), rule("inprogress", "false"),
                               rule("dateadded", "startswith", str(y)))


def main():
    out = ['<?xml version="1.0" encoding="UTF-8"?>',
           "<!-- GENERATED by _src/make_paths.py - smart-playlist content paths (url-encoded xsp). Do not edit. -->",
           "<includes>"]
    for name, path in PATHS.items():
        out.append(f'\t<variable name="KS_Path_{name}"><value>{path.replace("&", "&amp;")}</value></variable>')
    # the unwatched: path of the year on chip slot 0 / 1 (Container(8100) = the year chips)
    for slot in (0, 1):
        out.append(f'\t<variable name="KS_Path_UnwRow{slot}">')
        for y in UNW_YEARS:
            out.append(f'\t\t<value condition="String.IsEqual(Container(8100).ListItem({slot}).Property(year),y{y})">{PATHS[f"Waiting{y}"]}</value>')
        out.append(f'\t\t<value>{PATHS["Waiting2000"]}</value>')
        out.append("\t</variable>")
    out += ["</includes>", ""]
    OUT.write_text(finish_xml("\n".join(out)), encoding="utf-8", newline="\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
