"""Generate 1080i/Includes_Theme.xml: the Dark / Light room switch.   python skins/skin.groove/_src/make_theme.py

Reads colors/defaults.xml; every dk_<token> with an lt_<token> twin becomes a variable <token> that returns the
lt_ name in the Light room and the dk_ name otherwise. Windows write $VAR[<token>] (CONVENTIONS.md section 4).
Also writes the room expression, the per-room texture variables and the glow colour chain (SPEC section 11).
Re-run after adding a token to defaults.xml.
"""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
COLORS = ROOT / "colors" / "defaults.xml"
OUT = ROOT / "1080i" / "Includes_Theme.xml"

# The Light room is a skin setting. It falls back to Dark wherever the picture is the point (DESIGN_BRIEF:
# "playback OSD over video and the visualiser stay dark"): fullscreen video / live TV / games / slideshow and
# Now Playing while it shows the visualiser. Written out in full: window-level <visible>, <autoscroll> and
# Timers.xml don't expand $EXP (LESSONS), so copy LIGHT_COND there, not $EXP[GrooveLight].
LIGHT_COND = ("Skin.HasSetting(groove.light) + !VideoPlayer.IsFullscreen + !Window.IsActive(fullscreenlivetv)"
              " + !Window.IsActive(fullscreengame) + !Window.IsActive(slideshow)"
              " + ![Window.IsActive(visualisation) + Skin.HasSetting(groove.np.viz)]")

# per-room textures (designer's convention: media/groove/dark/<name>.png and media/groove/light/<name>.png)
ROOM_TEX = {
    "Tex_Room": "room.png",
    "Tex_Shelf": "shelf.png",
    "Tex_CrateBack": "crate_back.png",
    "Tex_CrateFront": "crate_front.png",
    "Tex_SleeveBack": "sleeve_back.png",
}


# Tokens with no bare-name variable (the official review, kdk variables.unused, flags a variable nothing reads):
# the wash alphas are read only through the `wash` variable below (as dk_ / lt_ names); header_rest, dim_stage and
# halo are in the palette (DESIGN 2 / 12) but no window uses them yet. Take a name off this list when one does.
NO_VARIABLE = {"wash_soft", "wash_medium", "wash_vivid", "header_rest", "dim_stage", "halo"}


def main():
    names = re.findall(r'<color name="dk_([a-z_0-9]+)">', COLORS.read_text(encoding="utf-8"))
    light = set(re.findall(r'<color name="lt_([a-z_0-9]+)">', COLORS.read_text(encoding="utf-8")))
    missing = [n for n in names if n not in light]
    assert not missing, f"dk_ tokens without an lt_ twin: {missing}"
    o = ['<?xml version="1.0" encoding="UTF-8"?>',
         "<!-- GENERATED by _src/make_theme.py from colors/defaults.xml - edit there / in the generator, then re-run.",
         "     The Dark / Light room: CONVENTIONS.md section 4. Windows use $VAR[<token>] for every colour. -->",
         "<includes>",
         f"\t<expression name=\"GrooveLight\">{LIGHT_COND}</expression>",
         "",
         "\t<!-- room tokens -->"]
    for n in names:
        if n in NO_VARIABLE:
            continue
        o += [f'\t<variable name="{n}">',
              f'\t\t<value condition="$EXP[GrooveLight]">lt_{n}</value>',
              f"\t\t<value>dk_{n}</value>",
              "\t</variable>"]
    o += ["", "\t<!-- per-room textures -->",
          '\t<variable name="Groove_RoomDir">',
          '\t\t<value condition="$EXP[GrooveLight]">light</value>',
          "\t\t<value>dark</value>",
          "\t</variable>"]
    for var, fn in ROOM_TEX.items():
        o += [f'\t<variable name="{var}">',
              f'\t\t<value condition="$EXP[GrooveLight]">groove/light/{fn}</value>',
              f"\t\t<value>groove/dark/{fn}</value>",
              "\t</variable>"]
    o += ["",
          "\t<!-- The glow colour (SPEC section 11): first source with a value wins. Every source is optional.",
          "\t     1 script.karmamole.helper  Window(Home).Property(Groove.Color.Main)   AARRGGBB, focused item after 400 ms rest",
          "\t     2 TMDb Helper           Window(Home).Property(TMDbHelper.ListItem.Colors.Main)  (setting groove.notmdbcolours off)",
          "\t     3 service.vizpalette    Window(Home).Property(VizPalette.Color1)   AARRGGBB, while music plays",
          "\t     4 glow_fallback         warm white (Dark) / warm sand (Light) -->",
          '\t<variable name="glow">',
          '\t\t<value condition="$EXP[HasGrooveHelper] + !String.IsEmpty(Window(Home).Property(Groove.Color.Main))">$INFO[Window(Home).Property(Groove.Color.Main)]</value>',
          '\t\t<value condition="!Skin.HasSetting(groove.notmdbcolours) + Skin.HasSetting(TMDbHelper.EnableColors) + !String.IsEmpty(Window(Home).Property(TMDbHelper.ListItem.Colors.Main))">$INFO[Window(Home).Property(TMDbHelper.ListItem.Colors.Main)]</value>',
          '\t\t<value condition="Player.HasAudio + $EXP[HasVizPalette] + !String.IsEmpty(Window(Home).Property(VizPalette.Color1))">$INFO[Window(Home).Property(VizPalette.Color1)]</value>',
          '\t\t<value condition="$EXP[GrooveLight]">lt_glow_fallback</value>',
          "\t\t<value>dk_glow_fallback</value>",
          "\t</variable>",
          "\t<!-- room wash alpha = Glow strength x room (DESIGN 12.3: Dark 25/40/60 %, Light 14/22/32 %) -->",
          '\t<variable name="wash">',
          '\t\t<value condition="$EXP[GrooveLight] + String.IsEqual(Skin.String(groove.glow),soft)">lt_wash_soft</value>',
          '\t\t<value condition="$EXP[GrooveLight] + String.IsEqual(Skin.String(groove.glow),vivid)">lt_wash_vivid</value>',
          '\t\t<value condition="$EXP[GrooveLight]">lt_wash_medium</value>',
          '\t\t<value condition="String.IsEqual(Skin.String(groove.glow),soft)">dk_wash_soft</value>',
          '\t\t<value condition="String.IsEqual(Skin.String(groove.glow),vivid)">dk_wash_vivid</value>',
          "\t\t<value>dk_wash_medium</value>",
          "\t</variable>",
          "\t<!-- The playing album's colour (HELPER_API 6): helper > TMDb Helper image_colors of this cover (Timers.xml",
          "\t     groove_np_colours) > vizpalette accent > vizpalette dominant > fallback. Now Playing (NP_Glow), the Liner",
          "\t     notes and Home's Music stage while music plays all read it. -->",
          '\t<variable name="glow_playing">',
          '\t\t<value condition="$EXP[HasGrooveHelper] + !String.IsEmpty(Window(Home).Property(Groove.Player.Color.Main))">$INFO[Window(Home).Property(Groove.Player.Color.Main)]</value>',
          '\t\t<value condition="!Skin.HasSetting(groove.notmdbcolours) + !String.IsEmpty(Window(Home).Property(TMDbHelper.GroovePlayer.Colors.Main)) + String.IsEqual(Window(Home).Property(groove.np.colorsrc),Player.Art(thumb))">$INFO[Window(Home).Property(TMDbHelper.GroovePlayer.Colors.Main)]</value>',
          '\t\t<value condition="$EXP[HasVizPalette] + !String.IsEmpty(Window(Home).Property(VizPalette.Color3))">$INFO[Window(Home).Property(VizPalette.Color3)]</value>',
          '\t\t<value condition="$EXP[HasVizPalette] + !String.IsEmpty(Window(Home).Property(VizPalette.Color1))">$INFO[Window(Home).Property(VizPalette.Color1)]</value>',
          '\t\t<value condition="$EXP[GrooveLight]">lt_glow_fallback</value>',
          "\t\t<value>dk_glow_fallback</value>",
          "\t</variable>",
          "</includes>", ""]
    OUT.write_text("\n".join(o), encoding="utf-8", newline="\n")
    print(f"wrote {OUT.name}: {len(names)} room tokens, {len(ROOM_TEX)} room textures")


if __name__ == "__main__":
    main()
