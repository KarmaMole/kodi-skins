"""Generate skins/skin.void/1080i/Includes_Rotary.xml: the rotary text index (VoidIndex mockup).

Kodi item layouts can't vary per distance from focus, so the rotary is drawn with 15 static labels
reading Container(<id>).ListItemNoWrap(-7..+7); the real (invisible) fixedlist drives focus.
Sizes, alphas and spacing are the mockup's: size [132, 68, 52, 42, 35, 30, 26, 24], alpha
[1, .46, .36, .29, .24, .20, .17, .15], line-height 1.12 (focus) / 1.1, gap 6, centred on y=540,
left 152 / 157 / 160. Positions are converted from CSS boxes to Kodi tops with Void's normalised
serif metrics (baseline = top + ceil(0.80 x size) with aligny top; CSS baseline = top + size x
(line-height / 2 + 0.34) for Instrument Serif's 0.99 / 0.31 em ascent / descent).

Also generates the A-Z letter column (scrubber) and the per-offset label variables ("Back" for
the parent-folder item).  Usage:  python skins/skin.void/_src/make_rotary.py
"""
import math
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE.parent / "1080i" / "Includes_Rotary.xml"

SIZE = [132, 68, 52, 42, 35, 30, 26, 24]
COLOR = ["text", "d1", "d2", "d3", "d4", "d5", "d6", "d7"]
FONT = [f"serif_{s}" for s in SIZE]
GAP = 6
F = 7


def lh(d):
    return 1.12 if d == 0 else 1.1


H = [s * lh(d) for d, s in enumerate(SIZE)]
OFF = [0.0]
for d in range(1, len(SIZE)):
    OFF.append(OFF[d - 1] + H[d - 1] / 2 + H[d] / 2 + GAP)


def row_geom(k):
    d = abs(k)
    centre = 540 + (1 if k > 0 else -1) * OFF[d] if k else 540
    css_top = centre - H[d] / 2
    baseline = css_top + SIZE[d] * (lh(d) / 2 + 0.34)
    top = round(baseline - math.ceil(0.80 * SIZE[d]))
    left = 152 if d == 0 else (157 if d == 1 else 160)
    height = math.ceil(0.80 * SIZE[d]) + math.ceil(0.24 * SIZE[d]) + 2
    return left, top, height, FONT[d], COLOR[d]


def main():
    out = ['<?xml version="1.0" encoding="UTF-8"?>',
           "<!-- GENERATED by _src/make_rotary.py - edit the generator, not this file. -->",
           "<includes>"]
    # label variables per offset (param-free: rotary always reads container 50)
    for k in range(-F, F + 1):
        if k == 0 or row_geom(k)[1] < 180:
            continue  # the focused row has Rotary_0; rows above y 180 are not drawn (see the column below)
        li = f"Container(50).ListItemNoWrap({k})"
        out.append(f'\t<variable name="Rotary_{"m" if k < 0 else "p"}{abs(k)}">')
        out.append(f'\t\t<value condition="{li}.IsParentFolder">Back</value>')
        out.append(f"\t\t<value>$INFO[{li}.Label]</value>")
        out.append("\t</variable>")
    out.append('\t<variable name="Rotary_0">')
    out.append('\t\t<value condition="Container(50).ListItem.IsParentFolder">Back</value>')
    out.append('\t\t<value condition="!String.IsEmpty(Container(50).ListItem.Title) + !Container.Content(files) + !Container.Content(addons)">$INFO[Container(50).ListItem.Title]</value>')
    out.append("\t\t<value>$INFO[Container(50).ListItem.Label]</value>")
    out.append("\t</variable>")

    # the column
    out.append('\t<include name="Rotary_Column">')
    out.append("\t\t<control type=\"group\">")
    out.append("\t\t\t<include content=\"Void_Anim_Roll\"><param name=\"id\" value=\"50\"/><param name=\"dist\" value=\"28\"/></include>")
    for k in range(-F, F + 1):
        left, top, height, font, color = row_geom(k)
        var = "Rotary_0" if k == 0 else f'Rotary_{"m" if k < 0 else "p"}{abs(k)}'
        if k == 0:
            # focused row: fitted to the width (Includes_Titles.xml Title_Rotary), never clipped
            out.append("""			<include content="Title_Rotary">
				<param name="label" value="$VAR[Rotary_0]"/>
				<param name="p0" value="7831"/>
				<param name="p1" value="7832"/>
				<param name="p2" value="7833"/>
			</include>""")
        elif top < 180:
            continue  # clear air under the section label
        else:
            out.append(f"""			<control type="label">
				<left>{left}</left>
				<top>{top}</top>
				<width>1100</width>
				<height>{height}</height>
				<aligny>top</aligny>
				<font>{font}</font>
				<textcolor>{color}</textcolor>
				<label>$VAR[{var}]</label>
			</control>""")
    out.append("\t\t</control>")
    out.append("\t</include>")

    # A-Z scrubber: rule at x 1744 (176..904), letters 28 px apart at x 1752
    out.append('\t<include name="Rotary_Letters">')
    out.append("""		<control type="group">
			<visible>$EXP[SortIsAlpha] + Integer.IsGreater(Container(50).NumItems,12)</visible>
			<control type="image">
				<left>1744</left>
				<top>176</top>
				<width>1</width>
				<height>728</height>
				<texture colordiffuse="hairline">common/white.png</texture>
			</control>""")
    for n, c in enumerate("ABCDEFGHIJKLMNOPQRSTUVWXYZ"):
        top = 176 + n * 28
        on = f"String.IsEqual(Container(50).ListItem.SortLetter,{c})"
        out.append(f"""			<control type="label">
				<left>1752</left>
				<top>{top}</top>
				<width>24</width>
				<height>28</height>
				<align>center</align>
				<font>sans_20_med</font>
				<textcolor>letter_off</textcolor>
				<label>[UPPERCASE]{c}[/UPPERCASE]</label>
				<visible>!{on}</visible>
			</control>
			<control type="label">
				<left>1750</left>
				<top>{top}</top>
				<width>28</width>
				<height>28</height>
				<align>center</align>
				<font>sans_22_semi</font>
				<textcolor>text</textcolor>
				<label>[UPPERCASE]{c}[/UPPERCASE]</label>
				<visible>{on}</visible>
			</control>""")
    out.append("\t\t</control>")
    out.append("\t</include>")
    out.append("</includes>\n")
    OUT.write_text("\n".join(out), encoding="utf-8", newline="\n")
    for k in range(0, F + 1):
        print(k, row_geom(k), row_geom(-k)[1])
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
