"""Generate skins/skin.void/1080i/DialogKeyboard.xml (on-screen keyboard).

Id contract copied from reference/skin.estuary-omega/xml/DialogKeyboard.xml:
  311 heading, 312 edit, keys 100-112 / 120-132 / 140-152 / 160-172 (Kodi writes the
  characters), 304 symbols, 303 caps lock, 302 shift, 32 space, 305 left, 306 right,
  8 backspace, side buttons 300 done / 301 cancel / 310 layout / 309 voice-or-IP / 307 IP,
  313 / 314 secondary input labels.
The autocompletion panel 9010 (needs plugin.program.autocompletion) is intentionally omitted.

Layout (Void): full-screen 92% black; caps heading, the typed text in serif 96 on an underline
(the edit control's own texture), IME candidate lines 313 / 314 under it (CJK input only), the
keys as bare characters in a 13 x 4 grid from x 160 / y 430 (no key caps: the focused character
turns white and grows 40%), a caps function row, and the side actions as text in a column at x 1500.

Usage:  python skins/skin.void/_src/make_keyboard.py
"""
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "1080i" / "DialogKeyboard.xml"

ROWS, COLS = 4, 13
KEY_W, KEY_H, GAP = 96, 84, 0  # keep in sync with constants kb_key_w / kb_key_h
FUNC = [  # id, label, width, columns it maps to (for up/down), type
    (304, "$LOCALIZE[31330]", 192, [0, 1], "radiobutton"),
    (303, "$LOCALIZE[31331]", 96, [2], "radiobutton"),
    (302, "$LOCALIZE[31332]", 96, [3], "radiobutton"),
    (32, "$LOCALIZE[31333]", 384, [4, 5, 6, 7], "button"),
    (305, "←", 96, [8], "button"),
    (306, "→", 96, [9], "button"),
    (8, "$LOCALIZE[31044]", 288, [10, 11, 12], "button"),
]
SIDE = [(300, "$LOCALIZE[12321]"), (301, "$LOCALIZE[222]"), (310, ""), (309, ""), (307, "$LOCALIZE[1006]")]


def key_id(r, c):
    return 100 + 20 * r + c


def func_for_col(c):
    for fid, _l, _w, cols, _t in FUNC:
        if c in cols:
            return fid
    raise ValueError(c)


def key_button(r, c, t):
    up = key_id(r - 1, c) if r > 0 else func_for_col(c)
    down = key_id(r + 1, c) if r < ROWS - 1 else func_for_col(c)
    return (f'{t}<control type="button" id="{key_id(r, c)}">\n'
            f'{t}\t<width>kb_key_w</width>\n{t}\t<height>kb_key_h</height>\n'
            f'{t}\t<include>Void_KeyboardKey</include>\n'
            f'{t}\t<onup>{up}</onup>\n{t}\t<ondown>{down}</ondown>\n'
            f'{t}</control>')


def func_button(fid, label, width, cols, ctype, t):
    up = key_id(ROWS - 1, cols[0])
    down = key_id(0, cols[0])
    extra = ""
    if ctype == "radiobutton":
        extra = (f'{t}\t<radiowidth>10</radiowidth>\n{t}\t<radioheight>10</radioheight>\n'
                 f'{t}\t<radioposx>{width // 2 - 5}</radioposx>\n{t}\t<radioposy>64</radioposy>\n')
    return (f'{t}<control type="{ctype}" id="{fid}">\n'
            f'{t}\t<width>{width}</width>\n{t}\t<height>kb_key_h</height>\n'
            f'{t}\t<label>{label}</label>\n'
            f'{t}\t<include>Void_KeyboardFunc</include>\n{extra}'
            f'{t}\t<onup>{up}</onup>\n{t}\t<ondown>{down}</ondown>\n'
            f'{t}</control>')


def main():
    t3, t4, t5 = "\t" * 3, "\t" * 4, "\t" * 5
    rows_xml = []
    for r in range(ROWS):
        keys = "\n".join(key_button(r, c, t5) for c in range(COLS))
        rows_xml.append(
            f'{t4}<control type="grouplist">\n{t5}<left>0</left>\n{t5}<top>{r * (KEY_H + GAP)}</top>\n'
            f'{t5}<width>1300</width>\n{t5}<height>kb_key_h</height>\n{t5}<orientation>horizontal</orientation>\n'
            + (f'{t5}<itemgap>{GAP}</itemgap>\n' if GAP else '')  # 0 = the grouplist default
            + f'{t5}<onleft>95200</onleft>\n{t5}<onright>95200</onright>\n'
            f'{keys}\n{t4}</control>')
    funcs = "\n".join(func_button(*f, t5) for f in FUNC)
    rows_xml.append(
        f'{t4}<control type="grouplist">\n{t5}<left>0</left>\n{t5}<top>{ROWS * (KEY_H + GAP)}</top>\n'
        f'{t5}<width>1300</width>\n{t5}<height>kb_key_h</height>\n{t5}<orientation>horizontal</orientation>\n'
        + (f'{t5}<itemgap>{GAP}</itemgap>\n' if GAP else '')  # 0 = the grouplist default
        + f'{t5}<onleft>95200</onleft>\n{t5}<onright>95200</onright>\n'
        f'{funcs}\n{t4}</control>')
    side = "\n".join(
        f'{t4}<include content="Void_DialogButton">\n{t5}<param name="id" value="{sid}"/>\n'
        f'{t5}<param name="label" value="{lab}"/>\n{t5}<param name="width" value="320"/>\n{t5}<param name="height" value="kb_key_h"/>\n{t5}<param name="align" value="left"/>\n{t4}</include>'
        for sid, lab in SIDE)

    xml = f'''<?xml version="1.0" encoding="UTF-8"?>
<!-- GENERATED by _src/make_keyboard.py - edit the generator, not this file.
     On-screen keyboard. Id contract: see the generator docstring (copied from Estuary Omega). -->
<window>
	<defaultcontrol always="true">300</defaultcontrol>
	<include>Anim_DialogOpenClose</include>
	<controls>
		<control type="group">
			<visible>!Window.IsVisible(numericinput)</visible>
			<include content="Dlg_Backdrop"><param name="color" value="f7000000"/></include>
			<control type="label" id="311">
				<left>160</left>
				<top>150</top>
				<width>1600</width>
				<height>24</height>
				<aligny>top</aligny>
				<font>caps_20</font>
				<textcolor>grey</textcolor>
			</control>
			<control type="edit" id="312">
				<left>152</left>
				<top>190</top>
				<width>1608</width>
				<height>132</height>
				<font>serif_96</font>
				<textcolor>text</textcolor>
				<textoffsetx>8</textoffsetx>
				<texturefocus border="0,0,0,3" colordiffuse="grey">common/underline.png</texturefocus>
			</control>
			<control type="label" id="313">
				<left>160</left>
				<top>336</top>
				<width>1600</width>
				<height>30</height>
				<font>sans_22</font>
				<textcolor>grey</textcolor>
			</control>
			<control type="label" id="314">
				<left>160</left>
				<top>370</top>
				<width>1600</width>
				<height>30</height>
				<font>sans_22</font>
				<textcolor>grey</textcolor>
			</control>
			<control type="group" id="78500">
				<left>160</left>
				<top>430</top>
{chr(10).join(rows_xml)}
			</control>
			<control type="grouplist" id="95200">
				<left>1484</left>
				<top>430</top>
				<width>340</width>
				<height>460</height>
				<orientation>vertical</orientation>
				<onleft>100</onleft>
				<onright>100</onright>
				<onup>95200</onup>
				<ondown>95200</ondown>
{side}
			</control>
			<control type="label">
				<left>160</left>
				<top>960</top>
				<width>1600</width>
				<height>24</height>
				<aligny>top</aligny>
				<font>caps_20</font>
				<textcolor>grey_soft</textcolor>
				<label>$LOCALIZE[31334][COLOR sep]  ·  [/COLOR]$LOCALIZE[31335]</label>
			</control>
		</control>
	</controls>
</window>
'''
    OUT.write_text(xml, encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
