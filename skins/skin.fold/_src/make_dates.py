"""Generate 1080i/Includes_Dates.xml: board-style dates ("11 Jun 2026", printed in caps) from Kodi's region dates.
    python skins/skin.fold/_src/make_dates.py

Kodi 21 can't format ListItem.DateAdded / Premiered / LastPlayed and has no substrings, but string tests work on
them. Omar's region prints dd/mm/yyyy (verified on the device for Passe-partout, LESSONS round 3), so:
  day = String.StartsWith(<label>,DD/), month = String.Contains(<label>,/MM/), year = String.Contains(<label>,/YYYY)
$VAR[Date_<key>] gives "11 Jun 2026", or the raw label when it isn't in that shape.

Month-first regions (0.9.12, Greptile on repo-skins #509): USA prints MM/DD/YYYY. Kodi has no infolabel for the
short-date order, so each date is read month-first when
  its middle field is over 12 (only possible as a day), or
  its first field is 12 or less AND the region's long date puts the month before the day.
The long-date test: Home.xml / Startup.xml onload store $INFO[System.Date(MMMM D)] ("October 25") in
Window(Home).Property(fold.monthday), and String.Contains(System.Date,<that property>) is true for
"Sunday, October 25, 2026" and false for "Sunday, 25 October 2026". It can't be written as
String.Contains(System.Date,System.Date(MMMM D)): Kodi lowercases the parameters of a condition, and lower-case
date tokens are the SHORT names (mmmm d = "Oct 25"; checked on the Kodi 21.2 bench). Kodi's region presets pair
MM/DD short dates with month-first long dates.
Day-first guard: on the 2nd and 20th "Friday, 20 October 2026" contains "October 20" (start of "October 2026"),
so the onloads also store $INFO[System.Date(MMMM YYYY)] in Window(Home).Property(fold.monthyear) and the test
requires the long date NOT to contain it ("October 2026" only appears when the day comes first).
"""
from pathlib import Path
from xmlfinish import finish_xml  # kodi-review labels.not-translated: label text goes to strings.po

OUT = Path(__file__).resolve().parents[1] / "1080i" / "Includes_Dates.xml"
MONTHS = "Jan Feb Mar Apr May Jun Jul Aug Sep Oct Nov Dec".split()
FIELDS = {
    "DA": "ListItem.DateAdded",
    "PR": "ListItem.Premiered",
    "LP": "ListItem.LastPlayed",
    "H9140": "Container(9140).ListItem.Premiered",
}
MD = "Window(Home).Property(fold.monthday)"
MY = "Window(Home).Property(fold.monthyear)"  # day-first guard (0.9.x region-test fix)


def main():
    out = ['<?xml version="1.0" encoding="UTF-8"?>',
           "<!-- GENERATED by _src/make_dates.py - board dates from dd/mm/yyyy and mm/dd/yyyy region dates. -->",
           "<includes>"]
    out.append(f'\t<expression name="Date_RegionMonthFirst">!String.IsEmpty({MD}) + String.Contains(System.Date,{MD}) + !String.Contains(System.Date,{MY})</expression>')
    for key, lab in FIELDS.items():
        first_big = " | ".join(f"String.StartsWith({lab},{d}/)" for d in range(13, 32))
        mid_big = " | ".join(f"String.Contains({lab},/{d}/)" for d in range(13, 32))
        out.append(f'\t<expression name="Date_{key}_MF">[{mid_big}] | [$EXP[Date_RegionMonthFirst] + ![{first_big}]]</expression>')
        out.append(f'\t<variable name="Date_{key}">')
        out.append(f'\t\t<value condition="String.Contains({lab},/)">$VAR[Date_{key}_D] $VAR[Date_{key}_M] $VAR[Date_{key}_Y]</value>')
        out.append(f'\t\t<value>$INFO[{lab}]</value>')
        out.append("\t</variable>")
        out.append(f'\t<variable name="Date_{key}_D">')
        for d in range(1, 32):
            out.append(f'\t\t<value condition="$EXP[Date_{key}_MF] + String.Contains({lab},/{d:02d}/)">[UPPERCASE]{d}[/UPPERCASE]</value>')
        for d in range(1, 32):
            out.append(f'\t\t<value condition="!$EXP[Date_{key}_MF] + String.StartsWith({lab},{d:02d}/)">[UPPERCASE]{d}[/UPPERCASE]</value>')
        out.append("\t</variable>")
        out.append(f'\t<variable name="Date_{key}_M">')
        for m, name in enumerate(MONTHS, 1):
            out.append(f'\t\t<value condition="$EXP[Date_{key}_MF] + String.StartsWith({lab},{m:02d}/)">{name}</value>')
        for m, name in enumerate(MONTHS, 1):
            out.append(f'\t\t<value condition="!$EXP[Date_{key}_MF] + String.Contains({lab},/{m:02d}/)">{name}</value>')
        out.append("\t</variable>")
        out.append(f'\t<variable name="Date_{key}_Y">')
        for y in range(2036, 1899, -1):
            out.append(f'\t\t<value condition="String.Contains({lab},/{y})">[UPPERCASE]{y}[/UPPERCASE]</value>')
        out.append("\t</variable>")
    out += ["</includes>", ""]
    OUT.write_text(finish_xml("\n".join(out)), encoding="utf-8", newline="\n")
    print("wrote", OUT.name)


if __name__ == "__main__":
    main()
