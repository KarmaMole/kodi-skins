"""Generate 1080i/Font.xml from one table (docs/skin.nocturne/DESIGN.md, type scale).

Two fontsets with the same names (Kodi has no glyph fallback): "Default" (Nocturne faces, built by make_fonts.py)
and "Arial" (Kodi's bundled arial.ttf, for scripts the faces don't cover).
Line pitch of every face = 1.21 em (normalised metrics), so linespacing = CSS line-height / 1.21.
    python skins/skin.nocturne/_src/make_fontxml.py
"""
