"""Generate 1080i/Includes_Diary.xml: the diary's overlay (mockups/KeepsakeDiary.html).

The diary (window 1161) is a fixedlist 520 (focusposition 1, movement 1: the focus rests on slot 0, 1 or 2 and the
timeline scrolls under it; the focused print is always fully on screen). Slot s: item top 176 + 128 s, print top
256 + 128 s. Container(520).Position = the focused slot P, so ListItemNoWrap(k) sits on slot P + k.
Month dividers (the month written in the gutter where it changes) are static controls between slots s-1 and s:
hidden labels 5208-5215 hold "Month Year" of ListItemNoWrap(-2..5); a divider shows when its two neighbours differ
(String.IsEqual(Control.GetLabel(a),Control.GetLabel(b))). Hidden while the list scrolls, written in after.
The sticky month above the timeline = the month of slot 0 (k = -P). The focused print's details sit beside it.
Usage: python skins/skin.keepsake/_src/make_diary.py
"""
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "1080i" / "Includes_Diary.xml"
KS = range(-2, 6)
LBL = {k: 5210 + k for k in KS}          # 5208 .. 5215
POS = (0, 1, 2)


def kname(k):
    return f"KS_DS{k}".replace("-", "m")


def main():
    o = ['<?xml version="1.0" encoding="UTF-8"?>',
         "<!-- GENERATED by _src/make_diary.py - the diary's month dividers, sticky month and details. -->",
         "<includes>", '\t<include name="Diary_Overlay">', '\t\t<control type="group">',
         '\t\t\t<visible>Control.IsVisible(520)</visible>']
    for k in KS:
        o += [f'\t\t\t<control type="label" id="{LBL[k]}">', '\t\t\t\t<left>-3000</left>', '\t\t\t\t<top>0</top>',
              '\t\t\t\t<width>400</width>', '\t\t\t\t<height>20</height>', '\t\t\t\t<font>lbl_20</font>',
              f'\t\t\t\t<label>$VAR[{kname(k)}_MonY]</label>', '\t\t\t</control>']
    # sticky month: slot 0 = k -P
    for p in POS:
        o += ['\t\t\t<control type="label">', '\t\t\t\t<left>760</left>', '\t\t\t\t<top>189</top>',
              '\t\t\t\t<width>400</width>', '\t\t\t\t<height>74</height>', '\t\t\t\t<align>center</align>',
              '\t\t\t\t<font>hand_54</font>', '\t\t\t\t<textcolor>ink</textcolor>',
              f'\t\t\t\t<label>$INFO[Control.GetLabel({LBL[-p]})]</label>',
              f'\t\t\t\t<visible>Integer.IsEqual(Container(520).Position,{p})</visible>', '\t\t\t</control>']
    # dividers
    for p in POS:
        for s in range(1, 6):
            kc, kp = s - p, s - 1 - p
            top = 424 + 128 * (s - 1)
            o += ['\t\t\t<control type="group">', '\t\t\t\t<left>0</left>', f'\t\t\t\t<top>{top}</top>',
                  '\t\t\t\t<width>1920</width>', '\t\t\t\t<height>80</height>',
                  f'\t\t\t\t<visible>Integer.IsEqual(Container(520).Position,{p}) + !Container(520).Scrolling + '
                  f'!String.IsEmpty(Control.GetLabel({LBL[kc]})) + !String.IsEmpty(Control.GetLabel({LBL[kp]})) + '
                  f'!String.IsEqual(Control.GetLabel({LBL[kp]}),Control.GetLabel({LBL[kc]}))</visible>',
                  '\t\t\t\t<animation effect="fade" start="0" end="100" time="220" delay="120">Visible</animation>',
                  '\t\t\t\t<control type="image">', '\t\t\t\t\t<left>790</left>', '\t\t\t\t\t<top>-12</top>',
                  '\t\t\t\t\t<width>340</width>', '\t\t\t\t\t<height>86</height>',
                  '\t\t\t\t\t<texture colordiffuse="paper">ks/erase.png</texture>', '\t\t\t\t</control>',
                  '\t\t\t\t<control type="label">', '\t\t\t\t\t<left>760</left>', '\t\t\t\t\t<top>0</top>',
                  '\t\t\t\t\t<width>400</width>', '\t\t\t\t\t<height>66</height>', '\t\t\t\t\t<align>center</align>',
                  '\t\t\t\t\t<font>hand_48</font>', '\t\t\t\t\t<textcolor>ink2</textcolor>',
                  f'\t\t\t\t\t<label>$VAR[{kname(kc)}_Disp]</label>', '\t\t\t\t</control>', '\t\t\t</control>']
    # the focused print's details: right page for even items, left page for odd
    for side, cond, left, align, x in (("right", "!Integer.IsOdd(Container(520).CurrentItem)", 1500, "left", 0),
                                        ("left", "Integer.IsOdd(Container(520).CurrentItem)", 112, "right", 140)):
        o += ['\t\t\t<control type="group">', f'\t\t\t\t<left>{left}</left>', '\t\t\t\t<top>268</top>',
              '\t\t\t\t<width>360</width>', '\t\t\t\t<height>320</height>',
              f'\t\t\t\t<visible>Control.HasFocus(520) + {cond}</visible>']
        for p in (1, 2):
            o.append(f'\t\t\t\t<animation effect="slide" end="0,{128 * p}" time="0" condition="Integer.IsEqual(Container(520).Position,{p})">Conditional</animation>')
        o += ['\t\t\t\t<animation effect="fade" start="0" end="100" time="200" delay="80">Visible</animation>',
              f'\t\t\t\t<include content="VidView_DiaryDetail"><param name="align" value="{align}"/><param name="x" value="{x}"/></include>',
              '\t\t\t</control>']
    o += ['\t\t</control>', '\t</include>', '</includes>', '']
    OUT.write_text("\n".join(o), encoding="utf-8", newline="\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
