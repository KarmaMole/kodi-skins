"""One-off fork pass: skin.majan engine -> skin.daylight (run once, 2026-10-18; kept for the record).

Reads the pristine XML from skins/skin.majan/1080i and writes skins/skin.daylight/1080i:
  * majan.* setting/property prefix -> daylight.*, Majan_ include names -> DL_, playlist names
  * removed Majan settings collapse to constants (rounded corners = always, focus outline = Daylight's own)
  * every Majan colour NAME used in a colour context -> a mood-aware token variable $VAR[DL_*]
    (tokens are defined in Includes_Daylight.xml, generated by make_time_vars.py)
  * Majan font names -> Daylight font names (Font.xml from make_fontxml.py)
  * windows that relied on <backgroundcolor>bg</backgroundcolor> get the DL_Background include

DO NOT re-run after hand edits: it overwrites 1080i/ from Majan.
"""
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "skin.majan" / "1080i"
DST = ROOT / "skin.daylight" / "1080i"

COLOR_MAP = {
    "text_primary": "DL_Ink", "text_body": "DL_Body", "text_secondary": "DL_Ink2", "text_tertiary": "DL_Ink3",
    "accent": "DL_Accent", "accent_signal": "DL_Accent",
    "hairline": "DL_Line", "hairline_soft": "DL_Line", "hairline_art": "DL_Line",
    "hairline_strong": "DL_Line2", "hairline_art_strong": "DL_Line2",
    "border_control": "DL_Line2", "border_button": "DL_Line2",
    "ink": "DL_OnAccent", "bg": "DL_Ground", "bg_raised": "DL_Raised", "bg_ghost": "DL_Surface",
    "disabled": "DL_Disabled", "scrim": "DL_Scrim", "scrim_track": "DL_ScrimTrack", "scrim_tab": "DL_ScrimTrack",
    "dim_row": "DL_DimArt", "dim_passed": "DL_DimArt", "dim_ahead": "DL_DimArt2",
    "dim_dialog": "DL_DimDialog", "dim_video": "DL_DimDialog",
    "shadow": "DL_Shadow", "focus_halo": "DL_Shadow",
    "art_faint": "DL_ArtAlpha", "art_soft": "DL_ArtAlpha", "art_visible": "DL_ArtAlpha",
}
VAR_MAP = {
    "ColorAccent": "DL_Accent", "ColorRule": "DL_Line", "ColorRuleStrong": "DL_Line2", "ColorCaption": "DL_Ink3",
}
FONT_MAP = {
    "mono_13": "cap_20", "mono_14": "cap_20", "mono_15": "cap_21", "mono_17": "cap_22",
    "num_14": "num_20", "num_16": "num_21", "num_22": "num_22", "Mono26": "num_26", "tab_13": "tab_20",
    "small_16": "small_20", "small_19": "small_20", "small_19_bold": "small_20_bold",
    "card_21": "ui_22", "card_21_medium": "ui_22", "card_21_bold": "ui_22_bold",
    "credits_21": "ui_22_reg", "credits_22": "ui_22_reg", "credits_21_semibold": "ui_22_semibold",
    "body_23": "body_24", "body_25": "body_24", "body_26": "body_26",
    "button_23_bold": "button_22", "button_23_semibold": "button_22_semibold",
    "section_24": "ui_24_semibold", "label_25_semibold": "ui_25_semibold", "label_25_bold": "ui_25_bold",
    "menu_26_bold": "ui_26_semibold", "menu_26_medium": "ui_26",
    "title_28_bold": "ui_28_bold", "title_28_medium": "ui_28", "title_28_semibold": "ui_28_semibold",
    "stat_30": "ui_30_semibold", "clock_34": "clock_30", "header_34": "serif_34",
    "display_48": "display_48", "display_64": "display_60", "display_68": "display_60",
    "display_72": "display_72", "display_92": "display_84", "display_100": "display_84", "ghost_220": "display_84",
}
COLOR_TAGS = "textcolor|focusedcolor|selectedcolor|disabledcolor|shadowcolor|invalidcolor|colordiffuse|color"


def tok(name: str) -> str:
    return f"$VAR[{COLOR_MAP[name]}]"


def transform(s: str) -> str:
    names = "|".join(sorted(COLOR_MAP, key=len, reverse=True))
    # colour attributes and tags
    s = re.sub(rf'\b({COLOR_TAGS})="({names})"', lambda m: f'{m.group(1)}="{tok(m.group(2))}"', s)
    s = re.sub(rf'<({COLOR_TAGS})>({names})</', lambda m: f'<{m.group(1)}>{tok(m.group(2))}</', s)
    s = re.sub(rf'\[COLOR ({names})\]', lambda m: f'[COLOR {tok(m.group(1))}]', s)
    # variable values / include params that are exactly a colour name
    s = re.sub(rf'(<value(?: condition="[^"]*")?>)({names})(</value>)', lambda m: m.group(1) + tok(m.group(2)) + m.group(3), s)
    s = re.sub(rf'(<param name="[^"]+" value=")({names})("\s*/>)', lambda m: m.group(1) + tok(m.group(2)) + m.group(3), s)
    s = re.sub(rf'(<param name="[^"]+">)({names})(</param>)', lambda m: m.group(1) + tok(m.group(2)) + m.group(3), s)
    for old, new in VAR_MAP.items():
        s = s.replace(f"$VAR[{old}]", f"$VAR[{new}]")
    # fonts
    fn = "|".join(sorted(FONT_MAP, key=len, reverse=True))
    s = re.sub(rf'<font>({fn})</font>', lambda m: f"<font>{FONT_MAP[m.group(1)]}</font>", s)
    s = re.sub(rf'(<param name="[^"]*font[^"]*" value=")({fn})(")', lambda m: m.group(1) + FONT_MAP[m.group(2)] + m.group(3), s)
    s = re.sub(rf'(<param name="[^"]*font[^"]*">)({fn})(</param>)', lambda m: m.group(1) + FONT_MAP[m.group(2)] + m.group(3), s)
    # removed settings -> constants
    s = s.replace("!Skin.HasSetting(majan.roundedcorners)", "false")
    s = s.replace("Skin.HasSetting(majan.roundedcorners)", "true")
    # names
    s = s.replace("TMDbHelper.MajanPlayer", "TMDbHelper.DaylightPlayer").replace("prefix=MajanPlayer", "prefix=DaylightPlayer")
    s = s.replace("special://skin/playlists/majan_", "special://skin/playlists/daylight_")
    s = s.replace("majan.", "daylight.").replace("Majan_", "DL_")
    s = s.replace("docs/skin.majan", "docs/skin.daylight").replace("skin.majan", "skin.daylight")
    # window background: static clear colour, the include draws the mood ground
    if "<backgroundcolor>bg</backgroundcolor>" in s:
        s = s.replace("<backgroundcolor>bg</backgroundcolor>", "<backgroundcolor>ff000000</backgroundcolor>")
        if "<include>DL_Background</include>" not in s:
            s = re.sub(r"(<controls>\s*\n)", r"\1\t\t<include>DL_Background</include>\n", s, count=1)
    return s


def main() -> None:
    if "--yes" not in sys.argv:
        sys.exit("refusing to overwrite 1080i/ without --yes (see docstring)")
    for f in sorted(SRC.glob("*.xml")):
        if f.name in ("Font.xml",):
            continue
        out = transform(f.read_text(encoding="utf-8"))
        (DST / f.name).write_text(out, encoding="utf-8", newline="\n")
    print("fork pass done")


if __name__ == "__main__":
    main()
