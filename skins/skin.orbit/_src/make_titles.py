"""Generate 1080i/Includes_Titles.xml: wide Archivo titles that always fit (no clipping).

Kodi 21 has no String.Length, but a TEXTBOX reports Container(id).NumPages (technique from the Duotone
build, see docs/LESSONS.md). For every title spot there are invisible probe textboxes (one per tier
except the last: same font and width as the tier, height = its line budget + half a line). NumPages > 1
means the title needs more lines than the tier allows, so the next, smaller tier shows.

Two includes per spot:
  Fit_<Name>          the tier textboxes, for use INSIDE a vertical grouplist (only the visible tier
                      takes space; heights are auto with a max of (lines-1) x pitch + 1.25 x size, so
                      the last line never loses glyph bottoms). params: label, top
  Fit_<Name>_Probes   the probes (alpha 0, off-screen). Put them anywhere in the same window, outside
                      the grouplist. param: label
Wide font line pitches (Font.xml linespacing targets): 84->96, 66->78, 56->66, 50->62, 44->54, 38->46, 34->44.

Usage: python skins/skin.orbit/_src/make_titles.py
"""
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "1080i" / "Includes_Titles.xml"
PITCH = {104: 118, 84: 96, 66: 78, 56: 66, 50: 62, 44: 54, 38: 46, 34: 44, 30: 38}

# name, width, tiers [(size, lines)], first probe id, comment
SPECS = [
    ("Home", 566, [(56, 2), (44, 3), (34, 4)], 9711, "Home poster panel title"),
    ("HomeMusic", 516, [(56, 2), (44, 3), (34, 4)], 9714, "Home album panel title"),
    ("HomeStation", 516, [(44, 2), (34, 3)], 9717, "Home settings station title"),
    ("SearchVideo", 566, [(56, 2), (44, 3), (34, 4)], 9721, "Search films / shows panel title"),
    ("SearchMusic", 516, [(56, 2), (44, 3), (34, 4)], 9724, "Search albums / artists panel title"),
    ("LibArc", 900, [(66, 2), (50, 3), (38, 4)], 9731, "Library arc info block title"),
    ("MusicArc", 780, [(66, 2), (50, 3), (38, 4)], 9734, "Music arc info block title"),
    ("Info", 1500, [(84, 2), (66, 2), (50, 3)], 9741, "Video info title"),
    ("MusicInfo", 1500, [(66, 2), (50, 3), (38, 4)], 9744, "Music info title"),
    ("OSD", 856, [(66, 2), (50, 3), (38, 4)], 9751, "Video OSD title"),
    ("NowPlaying", 856, [(66, 2), (50, 3), (38, 4)], 9754, "Music now playing title"),
]


def tier_height(size, lines):
    return round((lines - 1) * PITCH[size] + 1.25 * size)


def build():
    L = ['<?xml version="1.0" encoding="UTF-8"?>',
         "<!-- GENERATED by _src/make_titles.py - edit the generator, not this file.",
         "     Fit-to-width wide titles (probe textboxes + Container(id).NumPages). -->",
         "<includes>"]
    for name, width, tiers, pid0, desc in SPECS:
        L.append(f"\t<!-- {desc}: {width}px, tiers {tiers} -->")
        L.append(f'\t<include name="Fit_{name}">')
        L.append('\t\t<param name="top">0</param>')
        L.append('\t\t<param name="color">text_primary</param>')
        L.append("\t\t<definition>")
        for i, (size, lines) in enumerate(tiers):
            conds = [f"Integer.IsGreater(Container({pid0 + j}).NumPages,1)" for j in range(i)]
            if i < len(tiers) - 1:
                conds.append(f"!Integer.IsGreater(Container({pid0 + i}).NumPages,1)")
            L += ['\t\t\t<control type="textbox">', "\t\t\t\t<top>$PARAM[top]</top>",
                  f"\t\t\t\t<width>{width}</width>",
                  f'\t\t\t\t<height max="{tier_height(size, lines)}">auto</height>',
                  f"\t\t\t\t<font>wide_{size}</font>", "\t\t\t\t<textcolor>$PARAM[color]</textcolor>",
                  "\t\t\t\t<label>$PARAM[label]</label>",
                  f"\t\t\t\t<visible>{' + '.join(conds)}</visible>", "\t\t\t</control>"]
        L += ["\t\t</definition>", "\t</include>"]
        L.append(f'\t<include name="Fit_{name}_Probes">')
        L.append("\t\t<definition>")
        for i, (size, lines) in enumerate(tiers[:-1]):
            L += [f'\t\t\t<control type="textbox" id="{pid0 + i}">', "\t\t\t\t<left>-4000</left>",
                  f"\t\t\t\t<top>{-4000 + i * 400}</top>", f"\t\t\t\t<width>{width}</width>",
                  f"\t\t\t\t<height>{round((lines + 0.5) * PITCH[size])}</height>",
                  f"\t\t\t\t<font>wide_{size}</font>", "\t\t\t\t<textcolor>00ffffff</textcolor>",
                  "\t\t\t\t<label>$PARAM[label]</label>", "\t\t\t</control>"]
        L += ["\t\t</definition>", "\t</include>", ""]
    L.append("</includes>")
    OUT.write_text("\n".join(L) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    build()
