"""Generate skins/skin.duotone/1080i/Font.xml from one table (docs/skin.duotone/DESIGN.md section 3).

Two fontsets with identical names (Kodi has no per-glyph fallback):
  * "Default" - Anton (display, always uppercase) + Inter Tight 500/700 + the tracked caps derivative
  * "Arial"   - Kodi's bundled arial.ttf at the same sizes (Settings > Interface > Skin > Fonts) for
                titles in scripts Anton / Inter Tight don't cover.

Metrics (fontTools, see make_fonts.py output):
  Anton       natural line height 1.505 em, ascent 1.176 em, cap height 0.859 em
  Inter Tight natural line height 1.210 em, ascent 0.969 em
  Kodi linespacing = CSS line-height / natural line height.
  Placing Anton from a mockup: kodi_top = css_top - 0.302 * size (aligny top); aligny center
  centres Anton and Inter Tight capitals optically, so most labels use aligny center.

Usage:  python skins/skin.duotone/_src/make_fontxml.py
"""
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE.parent / "1080i" / "Font.xml"

AN = "Anton-Regular.ttf"
MED = "InterTight-Medium.ttf"
BOLD = "InterTight-Bold.ttf"
CAPS = "DuotoneCaps-Bold.ttf"          # Inter Tight 700, +0.14em (mockup .lb)
CAPST = "DuotoneCapsTight-Bold.ttf"    # Inter Tight 700, +0.06em (long caps strings, buttons)

ANTON_LS = 0.585   # CSS line-height .88 / 1.505
U = "uppercase"

# name, file, size, linespacing (None = font default), style
FONTS = [
    ("font13", MED, 26, None, None),                      # Kodi-required fallback
    # --- Anton display (always uppercase) ----------------------------------------------
    ("an_236", AN, 236, ANTON_LS, U),   # Home focused section, wall title, OSD time numerals
    ("an_200", AN, 200, ANTON_LS, U),   # info title (2 lines), music artist, info rating
    ("an_176", AN, 176, ANTON_LS, U),   # Home other sections
    ("an_150", AN, 150, ANTON_LS, U),   # music album title
    ("an_136", AN, 136, ANTON_LS, U),   # wall numerals
    ("an_104", AN, 104, ANTON_LS, U),   # spotlight title, dialog numerals
    ("an_88", AN, 88, ANTON_LS, U),     # Home clock, vertical "All" tile
    ("an_72", AN, 72, 0.63, U),         # tagline (line-height .95), page titles
    ("an_60", AN, 60, ANTON_LS, U),     # stats, clocks, numerals in rows
    ("an_48", AN, 48, 0.62, U),         # dialog headers, page headers
    ("an_40", AN, 40, ANTON_LS, U),     # action blocks
    ("an_32", AN, 32, ANTON_LS, U),     # track numbers, small numerals
    # --- tracked caps labels (Inter Tight 700, uppercase) -------------------------------
    ("cap_20", CAPS, 20, None, U),
    ("cap_24", CAPS, 24, None, U),
    ("capt_20", CAPST, 20, None, U),
    ("btn_24", CAPST, 24, None, U),     # dialog / settings buttons
    # --- Inter Tight 500 ---------------------------------------------------------------
    ("ui_22", MED, 22, None, None),
    ("ui_24", MED, 24, None, None),
    ("ui_26", MED, 26, None, None),
    ("body_24", MED, 24, 1.171, None),  # 34px lines
    ("body_26", MED, 26, 1.145, None),  # 36px lines
    # --- Inter Tight 700 ---------------------------------------------------------------
    ("bold_22", BOLD, 22, None, None),
    ("bold_24", BOLD, 24, None, None),
    ("bold_26", BOLD, 26, None, None),
    ("bold_28", BOLD, 28, None, None),
    # --- Estuary-name aliases for third-party script windows ----------------------------
    ("font10", MED, 22, None, None),
    ("font12", MED, 24, None, None),
    ("font14", MED, 28, None, None),
    ("font27", MED, 26, None, None),
    ("font30", BOLD, 32, None, None),
    ("font37", BOLD, 40, None, None),
    ("font45", AN, 48, None, U),
    ("font52_title", AN, 60, None, U),
    ("font45_title", AN, 48, None, U),
    ("font36_title", AN, 40, None, U),
    ("font30_title", BOLD, 32, None, None),
    ("font25_title", BOLD, 26, None, None),
    ("Mono26", MED, 26, None, None),
]


# Estuary font names kept for third-party script windows (add-on dialogs ask for them by name; Kodi only falls
# back to font13). kdk (the Kodi repository review bot) reports them as unused: each line carries a kdk-ignore.
ESTUARY_ALIASES = {"font10", "font12", "font14", "font27", "font30", "font37", "font45", "font52_title",
                   "font45_title", "font36_title", "font30_title", "font25_title"}
KDK_ALIAS = " <!-- kdk-ignore: fonts; Estuary font name kept for add-on script windows -->"


def font_xml(name, filename, size, ls, style):
    parts = [f"<name>{name}</name>", f"<filename>{filename}</filename>", f"<size>{size}</size>"]
    if ls is not None:
        parts.append(f"<linespacing>{ls}</linespacing>")
    if style:
        parts.append(f"<style>{style}</style>")
    return "\t\t<font>" + "".join(parts) + "</font>" + (KDK_ALIAS if name in ESTUARY_ALIASES else "")


def main():
    names = [f[0] for f in FONTS]
    assert len(names) == len(set(names)), "duplicate font name"
    out = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        "<!-- GENERATED by _src/make_fontxml.py - edit the table there, not this file. -->",
        "<!-- Type scale: docs/skin.duotone/DESIGN.md section 3. Licences: fonts/OFL-*.txt -->",
        "<fonts>",
        '\t<fontset id="Default" idloc="31900">',
    ]
    out += [font_xml(*f) for f in FONTS]
    out += ["\t</fontset>", "\t<!-- Fallback set: same names, Kodi's bundled arial.ttf (wider script coverage). -->",
            '\t<fontset id="Arial" idloc="31901">']
    for name, _file, size, ls, style in FONTS:
        # Arial is shorter than Anton: scale display sizes down so layouts keep their height
        sz = round(size * 0.82) if _file == AN else size
        out.append(font_xml(name, "arial.ttf", sz, None if _file == AN else ls, style))
    out += ["\t</fontset>", "</fonts>", ""]
    OUT.write_text("\n".join(out), encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({len(FONTS)} fonts per set)")


if __name__ == "__main__":
    main()
