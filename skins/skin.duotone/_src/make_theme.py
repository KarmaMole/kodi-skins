"""Generate 1080i/Includes_Theme.xml: the Look switch (Colour / Light / Dark).   python skins/skin.duotone/_src/make_theme.py

Reads colors/defaults.xml. Every co_<token> (with its lt_ / dk_ twins) becomes a variable <token> that returns
the lt_ name in the Light look, the dk_ name in the Dark look and the co_ name otherwise (a look whose value
equals Colour's is folded into the default). Windows write $VAR[<token>] (docs/skin.duotone/CONVENTIONS.md).
Also writes the look expressions, the section variables (SectionColor, SectionText/2/3, SectionFaint,
SectionTint, SectionPrint, formerly hand-written in Variables.xml) and the per-look texture variables.
Re-run after changing a value or adding a token in defaults.xml (and make_textures.py / make_view_previews.py,
which bake a few textures from these values).

The look is Skin.String(duotone.look): empty = Colour (the default), light, dark. Window-level <visible>,
<autoscroll> and Timers.xml don't expand $EXP (LESSONS 2): paste LOOK_LIGHT / LOOK_DARK there.
"""
from pathlib import Path

from theme_tokens import ROOT, palette, tokens

OUT = ROOT / "1080i" / "Includes_Theme.xml"

LOOK_LIGHT = "String.IsEqual(Skin.String(duotone.look),light)"
LOOK_DARK = "String.IsEqual(Skin.String(duotone.look),dark)"
LOOKCOND = {"lt": "$EXP[DT_LookLight]", "dk": "$EXP[DT_LookDark]", "co": ""}
# films is the section that is left over (Expressions.xml)
SECS = [("series", "$EXP[DT_SecSeries]"), ("music", "$EXP[DT_SecMusic]"), ("paper", "$EXP[DT_SecPaper]")]
MONO_OFF = "String.IsEqual(Skin.String(duotone.mono),off)"
MONO_LIGHT = "String.IsEqual(Skin.String(duotone.mono),light)"

# Which family carries text on each section's field, per look: "paper" = light text (cobalt is the one dark
# field of the Colour look). Anything not listed is "ink".
TEXT_ON = {"co": {"series": "paper"}, "lt": {}, "dk": {}}

# Tokens with no bare-name variable: nothing reads them directly (kdk variables.unused flags a variable nothing
# reads). They are still palette entries the section variables return. Take a name off when XML uses it.
NO_VARIABLE = {
    "ink_45", "ink_55", "ink_70", "ink_80", "paper_12", "paper_45",
    "tint_paper", "tintl_paper", "print_films", "print_series", "print_music", "print_paper",
} | {f"{fam}_{sec}" for fam in ("veil_ghost", "veil", "veill") for sec in ("films", "series", "music", "paper")}

# per-look textures (make_textures.py bakes them from the same palette)
TEXTURES = {
    "DT_TexWatched": {"lt": "markers/watched_light.png", "dk": "markers/watched_dark.png", "co": "markers/watched.png"},
    "DT_PanelTex": {"lt": "dialogs/panel_framed.png", "dk": "dialogs/panel_framed_dark.png", "co": "dialogs/panel_framed.png"},
}


def both(*conds):
    c = [x for x in conds if x]
    return " + ".join(c)


class Out:
    def __init__(self, pal):
        self.pal = pal
        self.o = []

    def var(self, name, values, comment=None):
        """values: [(condition, value)], the last one unconditional. Drops values that can't change the result."""
        if comment:
            self.o.append(f"\t<!-- {comment} -->")
        self.o.append(f'\t<variable name="{name}">')
        for cond, val in values:
            if cond:
                self.o.append(f'\t\t<value condition="{cond}">{val}</value>')
            else:
                self.o.append(f"\t\t<value>{val}</value>")
                break
        self.o.append("\t</variable>")

    def hexof(self, name):
        return self.pal.get(name, name)

    def section_values(self, fn, prefix=""):
        """fn(look, sec) -> colour name. Folds a look whose four sections share one value, and a look equal to Colour."""
        vals = []
        co = {s: fn("co", s) for s in ("films", "series", "music", "paper")}
        for look in ("lt", "dk", "co"):
            names = {s: fn(look, s) for s in ("films", "series", "music", "paper")}
            if look != "co" and all(self.hexof(names[s]) == self.hexof(co[s]) for s in names):
                continue  # same as the Colour look: the default values cover it
            lc = LOOKCOND[look]
            if len({self.hexof(n) for n in names.values()}) == 1:
                vals.append((both(prefix, lc), names["films"]))
                continue
            for sec, cond in SECS:
                if self.hexof(names[sec]) != self.hexof(names["films"]):
                    vals.append((both(prefix, lc, cond), names[sec]))
            vals.append((both(prefix, lc), names["films"]))
        return vals


def main():
    pal = palette()
    names = tokens()
    w = Out(pal)
    o = w.o
    o += ['<?xml version="1.0" encoding="UTF-8"?>',
          "<!-- GENERATED by _src/make_theme.py from colors/defaults.xml - edit there / in the generator, then re-run.",
          "     The Look setting (Colour / Light / Dark): docs/skin.duotone/CONVENTIONS.md. Windows use $VAR[<token>]",
          "     or a section variable for every colour; never co_ / lt_ / dk_ names, never hex. -->",
          "<includes>",
          f"\t<expression name=\"DT_LookLight\">{LOOK_LIGHT}</expression>",
          f"\t<expression name=\"DT_LookDark\">{LOOK_DARK}</expression>",
          f"\t<expression name=\"DT_LookMono\">{LOOK_LIGHT} | {LOOK_DARK}</expression>",
          "\t<!-- print veils (DESIGN 9.4 layers 3 / 5) are drawn only in Light / Dark with Monotone on -->",
          "\t<expression name=\"DT_PrintVeils\">$EXP[DT_LookMono] + $EXP[DT_MonoOn]</expression>",
          "\t<!-- section screens (DESIGN 9.5): Colour = dots everywhere; Light / Dark = films dots, series 45-degree",
          "\t     lines, music coarse dots, Search / Settings / system no screen. Same precedence as SectionColor. -->",
          "\t<expression name=\"DT_ScreenDots\">!$EXP[DT_LookMono] | [!$EXP[DT_SecSeries] + !$EXP[DT_SecMusic] + !$EXP[DT_SecPaper]]</expression>",
          "\t<expression name=\"DT_ScreenLines\">$EXP[DT_LookMono] + $EXP[DT_SecSeries]</expression>",
          "\t<expression name=\"DT_ScreenCoarse\">$EXP[DT_LookMono] + !$EXP[DT_SecSeries] + $EXP[DT_SecMusic]</expression>",
          "",
          "\t<!-- ============================================================ section variables (DESIGN.md 2) -->"]
    w.var("SectionColor", w.section_values(lambda L, s: f"{L}_sec_{s}"), "the field")

    def fam(L, s):
        return TEXT_ON[L].get(s, "ink")
    w.var("SectionText", w.section_values(lambda L, s: f"{L}_{fam(L, s)}"), "text and icons on the field")
    w.var("SectionText2", w.section_values(lambda L, s: f"{L}_{fam(L, s)}_80"), "secondary text on the field (80%)")
    w.var("SectionText3", w.section_values(lambda L, s: f"{L}_{fam(L, s)}_55"), "captions / disabled (55%)")
    w.var("SectionFaint", w.section_values(lambda L, s: f"{L}_paper_30" if fam(L, s) == "paper" else f"{L}_ink_26"),
          "ghosted display type: unfocused Home section names")
    tint = [(MONO_OFF, "white")]
    tint += w.section_values(lambda L, s: f"{L}_tintl_{s}", MONO_LIGHT)
    tint += w.section_values(lambda L, s: f"{L}_tint_{s}")
    w.var("SectionTint", tint, "monotone print tint (setting duotone.mono: empty = full print, light = soft wash, off = colour)")
    w.var("SectionPrint", w.section_values(lambda L, s: f"{L}_print_{s}"),
          "tint for a desaturated (TMDb Helper) source")
    w.var("SectionVeilGhost", [(MONO_OFF, "clear")] + w.section_values(lambda L, s: f"{L}_veil_ghost_{s}"),
          "layer 3 (DESIGN 9.4): field colour over the colour art, ghosts it; clear in Colour and with Monotone off")
    w.var("SectionVeil", [(MONO_OFF, "clear")] + w.section_values(lambda L, s: f"{L}_veill_{s}", MONO_LIGHT)
          + w.section_values(lambda L, s: f"{L}_veil_{s}"),
          "layer 5: field colour over the black-and-white source (veill with Monotone Light)")

    o += ["", "\t<!-- ============================================================ look tokens (colors/defaults.xml) -->"]
    count = 0
    for n in names:
        if n in NO_VARIABLE:
            continue
        vals = []
        for look in ("lt", "dk"):
            if pal[f"{look}_{n}"] != pal[f"co_{n}"]:
                vals.append((LOOKCOND[look], f"{look}_{n}"))
        vals.append(("", f"co_{n}"))
        w.var(n, vals)
        count += 1

    o += ["", "\t<!-- ============================================================ per-look textures -->"]
    for var, files in TEXTURES.items():
        vals = [(LOOKCOND[L], files[L]) for L in ("lt", "dk") if files[L] != files["co"]] + [("", files["co"])]
        w.var(var, vals)
    w.var("DT_PanelTint", [(LOOKCOND["dk"], "white"), ("", "$VAR[SectionColor]")],
          "Colour / Light: the white panel takes the field colour (its baked ink frame stays dark); Dark: baked panel, untinted")
    o += ["</includes>", ""]
    OUT.write_text("\n".join(o), encoding="utf-8", newline="\n")
    print(f"wrote {OUT.name}: {count} look tokens, {len(TEXTURES) + 1} texture variables")


if __name__ == "__main__":
    main()
