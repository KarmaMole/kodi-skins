"""Generate 1080i/Includes_Dates.xml: museum-label dates ("23 June 2026") from Kodi's region dates.

Kodi 21 has no date formatting for ListItem.DateAdded / Premiered / LastPlayed and no substrings, but
string tests work on them. Omar's region prints dd/mm/yyyy (verified on device), so:
  day   = 31 x String.StartsWith(<label>,DD/)    -> "23"   (leading zero dropped)
  month = 12 x String.Contains(<label>,/MM/)     -> "June"
  year  = String.Contains(<label>,/YYYY) 1900..2036
$VAR[Date_<key>] gives "23 June 2026", or the raw label when it isn't in that shape.

Month-first regions (0.9.21, ported from Fold 0.9.12): USA prints MM/DD/YYYY ("06/16/2024" printed "6  2024").
A date is read month-first when its middle field is over 12 (only possible as a day), or its first field is 12 or
less AND the region's long date puts the month before the day: Home.xml / Startup.xml onload store
$INFO[System.Date(MMMM D)] ("October 25") in Window(Home).Property(passepartout.monthday), and
String.Contains(System.Date,<that property>) is true for "Sunday, October 25, 2026", false for "Sunday, 25 October 2026".

Usage: python skins/skin.passepartout/_src/make_dates.py
Day-first guard: on the 2nd and 20th "Friday, 20 October 2026" contains "October 20" (start of "October 2026"),
so the onloads also store $INFO[System.Date(MMMM YYYY)] in Window(Home).Property(passepartout.monthyear) and the test
requires the long date NOT to contain it ("October 2026" only appears when the day comes first).
"""
from pathlib import Path
from localize import localize_xml  # literal label words -> $LOCALIZE[id] from strings.po (kdk labels.not-translated)
STRINGS_PO = Path(__file__).resolve().parent.parent / "language" / "resource.language.en_gb" / "strings.po"

OUT = Path(__file__).resolve().parents[1] / "1080i" / "Includes_Dates.xml"
MONTHS = "January February March April May June July August September October November December".split()
FIELDS = {
    "DA": "ListItem.DateAdded",
    "CDA": "Container.ListItem.DateAdded",
    "PR": "ListItem.Premiered",
    "CPR": "Container.ListItem.Premiered",
    "NPR": "Container(9350).ListItem.Premiered",
    "RPR": "Container(9120).ListItem.Premiered",
    "LP": "ListItem.LastPlayed",
    "CLP": "Container.ListItem.LastPlayed",
}
MD = "Window(Home).Property(passepartout.monthday)"
MY = "Window(Home).Property(passepartout.monthyear)"  # day-first guard (0.9.x region-test fix)


def main():
    out = ['<?xml version="1.0" encoding="UTF-8"?>',
           "<!-- GENERATED by _src/make_dates.py - museum-label dates from dd/mm/yyyy and mm/dd/yyyy region dates. -->",
           "<includes>"]
    out.append(f'	<expression name="Date_RegionMonthFirst">!String.IsEmpty({MD}) + String.Contains(System.Date,{MD}) + !String.Contains(System.Date,{MY})</expression>')
    for key, lab in FIELDS.items():
        first_big = " | ".join(f"String.StartsWith({lab},{d}/)" for d in range(13, 32))
        mid_big = " | ".join(f"String.Contains({lab},/{d}/)" for d in range(13, 32))
        out.append(f'	<expression name="Date_{key}_MF">[{mid_big}] | [$EXP[Date_RegionMonthFirst] + ![{first_big}]]</expression>')
        out.append(f'	<variable name="Date_{key}">')
        out.append(f'		<value condition="String.Contains({lab},/)">$VAR[Date_{key}_D] $VAR[Date_{key}_M] $VAR[Date_{key}_Y]</value>')
        out.append(f'		<value>$INFO[{lab}]</value>')
        out.append("	</variable>")
        out.append(f'	<variable name="Date_{key}_D">')
        for d in range(1, 32):
            # digit-only values are read as string ids (LESSONS 2): wrap them
            out.append(f'		<value condition="$EXP[Date_{key}_MF] + String.Contains({lab},/{d:02d}/)">[UPPERCASE]{d}[/UPPERCASE]</value>')
        for d in range(1, 32):
            out.append(f'		<value condition="!$EXP[Date_{key}_MF] + String.StartsWith({lab},{d:02d}/)">[UPPERCASE]{d}[/UPPERCASE]</value>')
        out.append("	</variable>")
        out.append(f'	<variable name="Date_{key}_M">')
        for m, name in enumerate(MONTHS, 1):
            out.append(f'		<value condition="$EXP[Date_{key}_MF] + String.StartsWith({lab},{m:02d}/)">{name}</value>')
        for m, name in enumerate(MONTHS, 1):
            out.append(f'		<value condition="!$EXP[Date_{key}_MF] + String.Contains({lab},/{m:02d}/)">{name}</value>')
        out.append("	</variable>")
        out.append(f'	<variable name="Date_{key}_Y">')
        for y in range(2036, 1899, -1):
            out.append(f'		<value condition="String.Contains({lab},/{y})">[UPPERCASE]{y}[/UPPERCASE]</value>')
        out.append("	</variable>")
    out += ["</includes>", ""]
    OUT.write_text(localize_xml("\n".join(out), STRINGS_PO), encoding="utf-8", newline="\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
