"""Generate the five-step room engine (SPEC section 5).   python skins/skin.vernissage/_src/make_rooms.py

Reads colors/defaults.xml (day_ / eve_ / duskN_ tokens), then writes
  * colors/defaults.xml, below its GENERATED marker: s1_ / s2_ / s3_ composite colours of every GROUND token
    (the Evening value laid over the Day value at that step's Evening-layer alpha, what the two-layer ground shows
    at rest), so a single $VAR can draw a ground where two layers can't;
  * 1080i/Includes_Rooms.xml: the step expressions, one variable per token, the room ground (Day layer under the
    Evening layer with one 300 ms Conditional fade per step), the light / shadow step fades and the room dir.
Other generators import this module for the condition TEXT (window-level <visible>, <autoscroll> and Timers.xml
don't expand $EXP, LESSONS): `import make_rooms as R; R.COND["dark"]`.

Steps (SPEC 5; architect's reading of "dawn runs the same steps in reverse from 7:00 am"):
  Evening begins at E (5 pm default, 6 pm, or the sunset table below): step 1 from E, 2 from E+5, 3 from E+10,
  4 (Evening) from E+15 until 7:00; dawn: 3 from 7:00, 2 from 7:05, 1 from 7:10, 0 (Day) from 7:15 until E.
  Settings (screens/Settings.md keywords): vernissage.room = auto (or empty) | day | evening (pins step 0 / 4);
  vernissage.evening = h17 (or empty) 5 pm | h18 6 pm | sunset; vernissage.debug.step = 0-4 (JSON-RPC only, screenshots; forces a step, never in Skin settings).
  Playback (fullscreen video / live TV / games / slideshow, the visualiser in Visualiser mode) is always step 4.
System.Time(HH:mm,HH:mm) is minute-of-day, region independent, start inclusive, end exclusive, wraps past midnight
(LESSONS Daylight). The month comes from Integer.IsEqual(System.Date(mm),N) (M1 probe, PROBES.md).
"""
from __future__ import annotations

import math
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
COLORS = ROOT / "colors" / "defaults.xml"
OUT = ROOT / "1080i" / "Includes_Rooms.xml"
MARK = "<!-- ===== GENERATED by _src/make_rooms.py: composite step colours of the ground tokens. Do not edit below. ===== -->"

EVE_ALPHA = (0, 15, 82, 92, 100)      # Evening layer alpha per step, % (SPEC 5)
SPOT_ALPHA = (0, 0, 60, 85, 100)      # the spotlight pool per step
SHADOW_ALPHA = (100, 80, 0, 0, 0)     # the Day shadow per step
STEP_MS = 300                         # each step change is one 300 ms fade (motion-designer owns the final set)
STEP_MIN = 5
DAWN = 7 * 60                         # dawn starts at 7:00 (SPEC 5, D)
GROUND = ("wall", "card", "card_edge", "rule", "placard_rule", "mat", "frame")
TEXT_SWITCH = 2                       # text / focus tokens use the Evening set from step 2 ("lights down")

# Sunset bucket: the 15th of each month at Omar's weather location (weather.gismeteo Location1 "Dubai", read
# read-only from addon_data on 2026-10-21), 25.2048 N 55.2708 E, UTC+4 (no daylight saving), rounded to the
# nearest quarter hour. Public users get the same table; it is "-ish" by design (SPEC 5).
LAT, LON, TZ = 25.2048, 55.2708, 4.0


def sunset_minutes(month: int, day: int = 15, year: int = 2026) -> int:
    """NOAA solar position (apparent sunset, zenith 90.833 deg), local clock minutes, unrounded."""
    n = (date_ordinal(year, month, day) - date_ordinal(year, 1, 1)) + 1
    g = 2 * math.pi / 365 * (n - 1 + (18 - 12) / 24)
    eqt = 229.18 * (0.000075 + 0.001868 * math.cos(g) - 0.032077 * math.sin(g) - 0.014615 * math.cos(2 * g)
                    - 0.040849 * math.sin(2 * g))
    decl = (0.006918 - 0.399912 * math.cos(g) + 0.070257 * math.sin(g) - 0.006758 * math.cos(2 * g)
            + 0.000907 * math.sin(2 * g) - 0.002697 * math.cos(3 * g) + 0.00148 * math.sin(3 * g))
    lat = math.radians(LAT)
    ha = math.degrees(math.acos(math.cos(math.radians(90.833)) / (math.cos(lat) * math.cos(decl))
                                - math.tan(lat) * math.tan(decl)))
    utc = 720 - 4 * (LON - ha) - eqt
    return utc + TZ * 60


def date_ordinal(y, m, d):
    import datetime
    return datetime.date(y, m, d).toordinal()


SUNSET = {m: int(round(sunset_minutes(m) / 15.0) * 15) for m in range(1, 13)}


def hm(minutes: int) -> str:
    minutes %= 24 * 60
    return f"{minutes // 60:02d}:{minutes % 60:02d}"


def win(a: int, b: int) -> str:
    return f"System.Time({hm(a)},{hm(b)})"


def step_windows(e: int) -> dict[int, str]:
    """Time windows (OR-ed) for each step with Evening beginning at minute e."""
    d, s = DAWN, STEP_MIN
    return {
        0: win(d + 3 * s, e),
        1: f"{win(e, e + s)} | {win(d + 2 * s, d + 3 * s)}",
        2: f"{win(e + s, e + 2 * s)} | {win(d + s, d + 2 * s)}",
        3: f"{win(e + 2 * s, e + 3 * s)} | {win(d, d + s)}",
        4: win(e + 3 * s, d),
    }


S_ROOM = "Skin.String(vernissage.room)"
S_EVE = "Skin.String(vernissage.evening)"
S_DBG = "Skin.String(vernissage.debug.step)"
AUTO = f"!String.IsEqual({S_ROOM},day) + !String.IsEqual({S_ROOM},evening)"
FIVE = f"!String.IsEqual({S_EVE},h18) + !String.IsEqual({S_EVE},sunset)"
SIX = f"String.IsEqual({S_EVE},h18)"
SUN = f"String.IsEqual({S_EVE},sunset)"
PLAYBACK = ("[VideoPlayer.IsFullscreen | Window.IsActive(fullscreenlivetv) | Window.IsActive(fullscreengame)"
            " | Window.IsActive(slideshow) | [Window.IsActive(visualisation) + Skin.HasSetting(vernissage.np.viz)]]")


def room_step(k: int) -> str:
    """The room's step k, ignoring playback."""
    w5, w6 = step_windows(17 * 60)[k], step_windows(18 * 60)[k]
    sun = " | ".join(f"[Integer.IsEqual(System.Date(mm),{m}) + [{step_windows(e)[k]}]]" for m, e in SUNSET.items())
    auto = f"[{AUTO} + [[{FIVE} + [{w5}]] | [{SIX} + [{w6}]] | [{SUN} + [{sun}]]]]"
    forced = {0: f" | String.IsEqual({S_ROOM},day)", 4: f" | String.IsEqual({S_ROOM},evening)"}.get(k, "")
    return (f"[[!String.IsEmpty({S_DBG}) + String.IsEqual({S_DBG},{k})] | "
            f"[String.IsEmpty({S_DBG}) + [{auto}{forced}]]]")


def conditions() -> dict[str, str]:
    c = {f"room{k}": room_step(k) for k in range(5)}
    for k in range(4):
        c[f"s{k}"] = f"![{PLAYBACK}] + {c[f'room{k}']}"
    c["s4"] = f"[{PLAYBACK} | {c['room4']}]"
    c["dark"] = f"[{c['s2']} | {c['s3']} | {c['s4']}]"
    c["day"] = f"![{c['dark']}]"
    c["playback"] = PLAYBACK
    return c


COND = conditions()


# ------------------------------------------------------------------ palette
def read_palette():
    s = COLORS.read_text(encoding="utf-8")
    if MARK not in s:
        raise SystemExit(f"{COLORS.name}: generated-block marker missing")
    head = s[:s.index(MARK)]
    pal = {}
    for name, val in re.findall(r'<color name="([a-z0-9_]+)">([0-9a-fA-F]{8})</color>', head):
        pal[name] = val.lower()
    return s, head, pal


def composite(day: str, eve: str, a: float) -> str:
    """Evening (opaque) over Day (opaque) at alpha a."""
    d = [int(day[i:i + 2], 16) for i in (2, 4, 6)]
    e = [int(eve[i:i + 2], 16) for i in (2, 4, 6)]
    return "ff" + "".join(f"{round(x * (1 - a) + y * a):02x}" for x, y in zip(d, e))


def tokens(pal):
    names = []
    for n in pal:
        m = re.match(r"(day|eve)_(.+)", n)
        if m and m.group(2) not in names:
            names.append(m.group(2))
    for n in names:
        assert f"day_{n}" in pal and f"eve_{n}" in pal, f"token {n}: needs day_ and eve_"
    for t in GROUND:
        assert t in names, t
        assert pal[f"day_{t}"].startswith("ff") and pal[f"eve_{t}"].startswith("ff"), f"ground {t} must be opaque"
    return names


def step_value(pal, tok, k):
    """Colour NAME the token uses at step k."""
    if tok in GROUND:
        return {0: f"day_{tok}", 4: f"eve_{tok}"}.get(k, f"s{k}_{tok}")
    if f"dusk{k}_{tok}" in pal:
        return f"dusk{k}_{tok}"
    return f"day_{tok}" if k < TEXT_SWITCH else f"eve_{tok}"


def step_rgb(pal, tok, k):
    """The ARGB a token shows at step k (composites computed, overrides honoured)."""
    if tok in GROUND:
        return composite(pal[f"day_{tok}"], pal[f"eve_{tok}"], EVE_ALPHA[k] / 100)
    return pal[step_value(pal, tok, k)]


def used_as_var(tok):
    """True when some other 1080i file writes $VAR[tok] (so the variable is generated only when it is read)."""
    pat = re.compile(rf"\$(?:ESC)?VAR\[{re.escape(tok)}\]")
    return any(pat.search(f.read_text(encoding="utf-8")) for f in sorted(OUT.parent.glob("*.xml")) if f != OUT)


def fades(prefix_alpha, cond_key="s"):
    """Conditional fades that hold a layer at the given alpha per step (100 = no animation)."""
    o = []
    for k, a in enumerate(prefix_alpha):
        if a == 100:
            continue
        o.append(f'\t\t<animation effect="fade" start="100" end="{a}" time="{STEP_MS}" '
                 f'condition="$EXP[VN_S{k}]">Conditional</animation>')
    return "\n".join(o)


def full_image(tex, ind):
    t = "\t" * ind
    return [f'{t}<control type="image">', f"{t}\t<left>0</left>", f"{t}\t<top>0</top>", f"{t}\t<width>1920</width>",
            f"{t}\t<height>1080</height>", f"{t}\t<texture{tex}</texture>", f"{t}</control>"]


def room_layers():
    """VN_Room body: the Day layer (not drawn at step 4) under the Evening layer (not drawn at step 0; steps 1-3
    hold it at their alpha). Visible / Hidden fades + per-step Conditional fades, all STEP_MS (fades only, so no
    reduce-motion twin is needed, and one Hidden animation per control: LESSONS Groove device pass 2)."""
    vis = [f'\t\t\t\t<animation effect="fade" time="{STEP_MS}">Visible</animation>',
           f'\t\t\t\t<animation effect="fade" time="{STEP_MS}">Hidden</animation>']
    o = ['\t\t<control type="group">', "\t\t\t<left>0</left>", "\t\t\t<top>0</top>", "\t\t\t<width>1920</width>",
         "\t\t\t<height>1080</height>",
         "\t\t\t<!-- Day layer: flat wall + window wash (white alpha) + far corner (black alpha) -->",
         '\t\t\t<control type="group">', "\t\t\t\t<visible>!$EXP[VN_S4]</visible>", *vis]
    o += full_image(' colordiffuse="day_wall">vn/white.png', 4) + full_image(">vn/daylight.png", 4)
    o += full_image(">vn/dayfar.png", 4)
    o += ["\t\t\t</control>",
          "\t\t\t<!-- Evening layer: flat wall + edge falloff (black alpha) -->",
          '\t\t\t<control type="group">', "\t\t\t\t<visible>!$EXP[VN_S0]</visible>", *vis,
          fades((100,) + EVE_ALPHA[1:]).replace("\t\t<animation", "\t\t\t\t<animation")]
    o += full_image(' colordiffuse="eve_wall">vn/white.png', 4) + full_image(">vn/vignette.png", 4)
    o += ["\t\t\t</control>", "\t\t</control>"]
    return o


def main():
    s, head, pal = read_palette()
    names = tokens(pal)
    gen = [MARK]
    for t in GROUND:
        for k in (1, 2, 3):
            gen.append(f'<color name="s{k}_{t}">{step_rgb(pal, t, k)}</color>   <!-- step {k}: eve over day at {EVE_ALPHA[k]} % -->')
    COLORS.write_text(head + "\n\t".join(gen) + "\n</colors>\n", encoding="utf-8", newline="\n")

    o = ['<?xml version="1.0" encoding="UTF-8"?>',
         "<!-- GENERATED by _src/make_rooms.py from colors/defaults.xml - edit there / in the generator, then re-run.",
         "     The five light steps (SPEC 5, CONVENTIONS.md section 4). Windows use $VAR[<token>] for every colour and",
         "     $EXP[VN_Dark] / $EXP[VN_Day] (text set) or $EXP[VN_S0] .. $EXP[VN_S4] (step) for room-dependent layers.",
         f"     Sunset table (minute of day per month, Dubai): {', '.join(f'{m}={hm(e)}' for m, e in SUNSET.items())} -->",
         "<includes>",
         "\t<!-- steps: VN_RoomS<k> = the room's step (no playback gate); VN_S<k> = what the skin draws (playback is",
         "\t     always step 4). Exactly one VN_S<k> is true. -->",
         f"\t<expression name=\"VN_Playback\">{COND['playback']}</expression>"]
    for k in range(5):
        o.append(f'\t<expression name="VN_RoomS{k}">{COND[f"room{k}"]}</expression>')
    for k in range(4):
        o.append(f'\t<expression name="VN_S{k}">![$EXP[VN_Playback]] + $EXP[VN_RoomS{k}]</expression>')
    o.append('\t<expression name="VN_S4">$EXP[VN_Playback] | $EXP[VN_RoomS4]</expression>')
    o.append("\t<!-- the text set: Day ink in steps 0-1, Evening ink from step 2 (lights down) and over playback -->")
    o.append('\t<expression name="VN_Dark">$EXP[VN_S2] | $EXP[VN_S3] | $EXP[VN_S4]</expression>')
    o.append('\t<expression name="VN_Day">![$EXP[VN_S2] | $EXP[VN_S3] | $EXP[VN_S4]]</expression>')
    o.append("")
    o.append("\t<!-- room tokens: the colour NAME for the current step (first match wins). A token only the room twins")
    o.append("\t     read (day_ / eve_ names inside list layouts) gets no variable: the review flags unused variables. -->")
    for t in [n for n in names if used_as_var(n)]:
        vals = [step_value(pal, t, k) for k in range(5)]
        o.append(f'\t<variable name="{t}">')
        last = vals[4]
        k = 0
        while k < 4:
            j = k
            while j + 1 < 4 and vals[j + 1] == vals[k]:
                j += 1
            if vals[k] != last:
                cond = " | ".join(f"$EXP[VN_S{i}]" for i in range(k, j + 1))
                o.append(f'\t\t<value condition="{cond}">{vals[k]}</value>')
            k = j + 1
        o.append(f"\t\t<value>{last}</value>")
        o.append("\t</variable>")
    if used_as_var("VN_RoomDir"):   # only when some window reads it (the picker draws room twins since M2)
        o += ["",
              "\t<!-- per-room folder for baked room textures (view previews, prints): media/vn/<dir>/ -->",
              '\t<variable name="VN_RoomDir">',
              '\t\t<value condition="$EXP[VN_Day]">day</value>',
              "\t\t<value>evening</value>",
              "\t</variable>"]
    o += ["",
          "\t<!-- The room: the Day layer (flat wall + window wash + far corner) under the Evening layer (flat wall +",
          f"\t     edge falloff), whose alpha steps {' / '.join(map(str, EVE_ALPHA))} %. One {STEP_MS} ms fade per step change",
          "\t     (reversible Conditionals; motion-designer owns the final animation set, MOTION.md). First control of",
          "\t     every full-screen window. Window open / close fades go on the content group above it, never here. -->",
          '\t<include name="VN_Room">',
          *room_layers(),
          "\t</include>",
          "",
          "\t<!-- The spotlight pool's strength per step (" + " / ".join(map(str, SPOT_ALPHA)) + " %): put on the pool image (or its group). -->",
          '\t<include name="VN_SpotSteps">',
          fades(SPOT_ALPHA),
          "\t</include>",
          "\t<!-- The Day shadow's strength per step (" + " / ".join(map(str, SHADOW_ALPHA)) + " %): put on the shadow image. -->",
          '\t<include name="VN_ShadowSteps">',
          fades(SHADOW_ALPHA),
          "\t</include>",
          "</includes>", ""]
    OUT.write_text("\n".join(o), encoding="utf-8", newline="\n")
    print(f"wrote {OUT.name}: {len(names)} room tokens ({len(GROUND)} grounds composited), sunset table "
          + " ".join(f"{m}:{hm(e)}" for m, e in SUNSET.items()))


if __name__ == "__main__":
    main()
