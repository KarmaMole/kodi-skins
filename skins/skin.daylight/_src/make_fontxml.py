"""Generate skins/skin.daylight/1080i/Font.xml from one table (DESIGN.md section 4.3).

Why a generator: Daylight ships TWO fontsets that must define exactly the same
names (Kodi has no per-glyph fallback):
  * "Default" - Fraunces (soft, static instances) + Figtree
  * "Arial"   - Kodi's bundled arial.ttf at the same sizes, selectable in
                Settings > Interface > Skin > Fonts for titles in scripts the
                Daylight fonts don't cover (Arabic, CJK...). Estuary pattern.
Editing the table below and re-running keeps both sets in sync.

Usage:  python skins/skin.daylight/_src/make_fontxml.py
"""
from pathlib import Path

