"""Generate 1080i/Includes_Titles.xml: Geist Light titles that step down to fit instead of clipping.

Kodi 21 has no String.Length, but a textbox reports Container(id).NumPages (Duotone's technique, LESSONS
round 3): an invisible probe textbox per tier (same font and width, height = the tier's lines + half a
line); NumPages > 1 means the title needs more lines than the tier allows, so the next tier is shown.

Single-line slots (captions, OSD, dialog): every tier is a label of the slot's height with aligny center,
so a smaller step stays on the same centre line. The wall label title is a two-line textbox inside the
label's grouplist (auto height), so smaller steps also shorten the block.

Geist line pitch in Kodi = 1.2 x size x linespacing (make_fontxml.py).
Usage: python skins/skin.passepartout/_src/make_titles.py
"""
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "1080i" / "Includes_Titles.xml"
PITCH = {"disp_112": 132, "disp_96": 112, "ttl_72": 84, "ttl_64": 76, "ttl_56": 66, "ttl_48": 58, "ttl_44": 54, "ttl_40": 50}


def probe(pid, font, width, lines, label, align):
    return f'''				<control type="textbox" id="{pid}">
					<left>0</left>
					<top>0</top>
					<width>{width}</width>
					<height>{round(PITCH[font] * (lines + 0.5))}</height>
					<font>{font}</font>
					<align>{align}</align>
					<textcolor>00ffffff</textcolor>
					<label>{label}</label>
				</control>'''


def conds(pids, i, n):
    c = [f"Integer.IsGreater(Container({pids[j]}).NumPages,1)" for j in range(i)]
    if i < n - 1:
        c.append(f"!Integer.IsGreater(Container({pids[i]}).NumPages,1)")
    return " + ".join(c) or "true"


def single(name, width, height, tiers, base, label, align="left", color="ink"):
    pids = [base + i for i in range(len(tiers) - 1)]
    out = [f'\t<include name="{name}">', '\t\t<param name="left">0</param>', '\t\t<param name="top">0</param>',
           '\t\t<definition>', '\t\t\t<control type="group">', '\t\t\t\t<left>$PARAM[left]</left>',
           '\t\t\t\t<top>$PARAM[top]</top>', f'\t\t\t\t<width>{width}</width>', f'\t\t\t\t<height>{height}</height>']
    for pid, font in zip(pids, tiers):
        out.append(probe(pid, font, width, 1, label, align))
    for i, font in enumerate(tiers):
        out.append(f'''				<control type="label">
					<left>0</left>
					<top>0</top>
					<width>{width}</width>
					<height>{height}</height>
					<font>{font}</font>
					<align>{align}</align>
					<aligny>center</aligny>
					<textcolor>{color}</textcolor>
					<label>{label}</label>
					<visible>{conds(pids, i, len(tiers))}</visible>
				</control>''')
    out += ['\t\t\t</control>', '\t\t</definition>', '\t</include>']
    return "\n".join(out)


def wall_title():
    """Wall-label title: probes (one include, placed absolutely) + the visible textboxes (another include,
    used inside the label's grouplist)."""
    tiers = [("disp_112", 2), ("disp_96", 2), ("ttl_72", 3)]
    pids = [7301, 7302]
    label = "$VAR[VidInfo_Title]"
    probes = ['\t<include name="Title_WallProbes">', '\t\t<control type="group">', '\t\t\t<left>820</left>',
              '\t\t\t<top>128</top>']
    for pid, (font, lines) in zip(pids, tiers):
        probes.append(probe(pid, font, 900, lines, label, "left").replace("\t\t\t\t", "\t\t\t"))
    probes += ['\t\t</control>', '\t</include>']
    vis = ['\t<include name="Title_WallText">']
    for i, (font, lines) in enumerate(tiers):
        vis.append(f'''		<control type="textbox">
			<width>900</width>
			<height max="{PITCH[font] * lines}">auto</height>
			<font>{font}</font>
			<textcolor>ink</textcolor>
			<label>{label}</label>
			<visible>{conds(pids, i, len(tiers))}</visible>
		</control>''')
    vis.append('\t</include>')
    return "\n".join(probes) + "\n" + "\n".join(vis)


SPECS = [
    ("Title_Hang", 1280, 84, ["ttl_72", "ttl_56", "ttl_44"], 7201, "$VAR[VidView_Title]", "left"),
    ("Title_Series", 704, 84, ["ttl_72", "ttl_56", "ttl_44"], 7211, "$VAR[VidView_Title]", "left"),
    ("Title_Home", 1400, 88, ["ttl_72", "ttl_56", "ttl_44"], 7221, "$INFO[Container(9101).ListItem.Label]", "center"),
    ("Title_Music", 1260, 84, ["ttl_72", "ttl_56", "ttl_44"], 7231, "$VAR[Music_Title]", "left"),
    ("Title_OSD", 520, 76, ["ttl_64", "ttl_48", "ttl_40"], 7241, "$VAR[OSD_PPTitle]", "left"),
    ("Title_OSDWide", 1680, 76, ["ttl_64", "ttl_48", "ttl_40"], 7251, "$VAR[OSD_PPTitle]", "left"),
    ("Title_Context", 400, 76, ["ttl_64", "ttl_48", "ttl_40"], 7261, "$INFO[ListItem.Label]", "left"),
    ("Title_Room", 1680, 76, ["ttl_64", "ttl_48"], 7271, "$VAR[Home_RoomTitle]", "left"),
    ("Title_NowPlaying", 1600, 84, ["ttl_72", "ttl_56", "ttl_44"], 7281, "$INFO[MusicPlayer.Title]", "center"),
]


def main():
    parts = ['<?xml version="1.0" encoding="UTF-8"?>',
             '<!-- GENERATED by _src/make_titles.py - Geist Light titles fitted with probe textboxes + NumPages. -->',
             "<includes>"]
    parts += [single(*s) for s in SPECS]
    parts.append(wall_title())
    parts.append("</includes>\n")
    OUT.write_text("\n".join(parts), encoding="utf-8", newline="\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
