"""Generate 1080i/Includes_Titles.xml: fitted Anton mastheads (no scrolling, no clipping, no overlap).

Kodi 21 has no String.Length, but a TEXTBOX reports Container(id).NumPages (Estuary's DialogTextViewer
uses it). So each masthead carries invisible "probe" textboxes, one per tier except the last: same width
and font as the tier, height = the tier's line count (+ half a line). NumPages > 1 means the title needs
more lines than that tier allows, and the next (smaller / more lines) tier is shown. The last tier fits
every title in Omar's library (measured with PIL against all 1360 films, 284 shows, 5711 episodes,
229 albums, 155 artists on 2026-10-18).

Anton metrics in Kodi (measured on device): line pitch = 0.8804 x size (linespacing .585; .63 for an_72,
.62 for an_48), first-line cap top = textbox top + 0.535 x size, cap height 0.859 x size.

Usage: python skins/skin.duotone/_src/make_titles.py
"""
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "1080i" / "Includes_Titles.xml"
NATURAL = 1.505
LS = {72: 0.63, 48: 0.62}
NL = "\n"
TAB = "\t"


def pitch(size):
    return size * NATURAL * LS.get(size, 0.585)


def textbox(t, top, width, height, size, label, color, visible, tid=None, align="left"):
    idattr = f' id="{tid}"' if tid is not None else ""
    rows = [f'<control type="textbox"{idattr}>', "\t<left>0</left>", f"\t<top>{round(top)}</top>",
            f"\t<width>{width}</width>", f"\t<height>{round(height)}</height>", f"\t<align>{align}</align>",
            f"\t<font>an_{size}</font>", f"\t<textcolor>{color}</textcolor>", f"\t<label>{label}</label>",
            f"\t<visible>{visible}</visible>", "</control>"]
    return NL.join(t + r for r in rows)


def masthead(name, desc, width, tiers, probe_base, label, color="$VAR[SectionText]", align="left", pid=None, extra_params=()):
    """tiers: [(size, lines)]; the caps of the first line sit at the include's top (params left / top)."""
    pid = pid or (lambda k: probe_base + k)
    out = [f"\t<!-- {desc} -->", f'\t<include name="{name}">',
           '\t\t<param name="left">0</param>', '\t\t<param name="top">0</param>']
    out += [f'\t\t<param name="{p}"/>' for p in extra_params]
    out += ["\t\t<definition>", '\t\t\t<control type="group">', "\t\t\t\t<left>$PARAM[left]</left>",
            "\t\t\t\t<top>$PARAM[top]</top>", f"\t\t\t\t<width>{width}</width>"]
    t = TAB * 4
    for i, (size, lines) in enumerate(tiers[:-1]):
        out.append(textbox(t, -0.535 * size, width, pitch(size) * (lines + 0.5), size, label, "00ffffff", "true", tid=pid(i), align=align))
    for i, (size, lines) in enumerate(tiers):
        conds = [f"Integer.IsGreater(Container({pid(j)}).NumPages,1)" for j in range(i)]
        if i < len(tiers) - 1:
            conds.append(f"!Integer.IsGreater(Container({pid(i)}).NumPages,1)")
        h = (lines - 1) * pitch(size) + 1.5 * size
        out.append(textbox(t, -0.535 * size, width, h, size, label, color, " + ".join(conds) or "true", align=align))
    out += ["\t\t\t</control>", "\t\t</definition>", "\t</include>"]
    return NL.join(out)


SPECS = [
    # name, desc, width, tiers, first probe id, label
    ("Title_Wall", "Wall masthead (view 500): caps band y 158-362, x 58-948 (the numerals start at 976)",
     890, [(236, 1), (136, 1), (104, 2), (72, 3)], 7101, "$VAR[VidView_WallBigTitle]"),
    ("Title_Info", "Info title: caps band y 158-506, x 818-1858",
     1040, [(200, 2), (136, 2), (104, 3), (72, 4)], 7111, "$VAR[VidInfo_Title]"),
    ("Title_MusicArtist", "Music wall artist: caps band y 174-372, x 58-1098",
     1040, [(200, 1), (136, 1), (104, 2), (72, 2)], 7121, "$VAR[MusicWall_Artist]"),
    ("Title_MusicAlbum", "Music wall album: caps band y 462-600, x 1156-1856",
     700, [(150, 1), (104, 1), (72, 2), (48, 2)], 7131, "$VAR[MusicWall_Big]"),
    ("Title_Episode", "Episodes view title (left column): caps band from y 468, 680 wide",
     680, [(72, 2), (48, 3)], 7141, "$VAR[VidView_ItemTitle]"),
    ("Title_NowPlaying", "Now playing title: caps band y 246-430, 1128 wide",
     1128, [(104, 2), (72, 2), (48, 3)], 7151, "$INFO[MusicPlayer.Title]"),
    ("Title_OSD", "OSD title (right of the giant time): caps band 80 high, 1032 wide",
     1032, [(72, 1), (48, 1), (40, 2)], 7161, "$VAR[OSD_Title]"),
    ("Title_FSInfo", "Fullscreen info title: caps band 80 high, 1528 wide",
     1528, [(72, 1), (48, 1), (40, 2)], 7171, "$VAR[OSD_Title]"),
]


def main():
    parts = ['<?xml version="1.0" encoding="UTF-8"?>',
             "<!-- GENERATED by _src/make_titles.py - fitted Anton mastheads (probe textboxes + NumPages). -->",
             "<includes>"]
    for name, desc, width, tiers, base, label in SPECS:
        parts.append(masthead(name, desc, width, tiers, base, label))
    parts.append(masthead("Title_Spot", "Home spotlight title in the ink block, 968 wide, caps band 104 high. params: label, pb (probe id prefix)",
                          968, [(104, 1), (72, 1), (48, 2)], 0, "$PARAM[label]", color="paper",
                          pid=lambda k: f"$PARAM[pb]{k}", extra_params=("label", "pb")))
    parts.append("</includes>" + NL)
    OUT.write_text(NL.join(parts), encoding="utf-8", newline=NL)
    print("wrote", OUT)


if __name__ == "__main__":
    main()
