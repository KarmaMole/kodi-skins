"""Generate 1080i/Includes_Titles.xml: Fraunces titles that step down a size instead of clipping.

Kodi 21 has no String.Length, but a TEXTBOX reports Container(id).NumPages (Duotone's lesson,
docs/LESSONS.md). Each site gets invisible probe textboxes, one per tier except the last: same width
and font as the tier, height = the tier's line count + half a line. NumPages > 1 means the title
needs more lines than that tier allows, so the next tier (smaller font / more lines) is shown.

Per site three includes (param label):
  T_<site>_Title    the probes + one visible textbox per tier (place where the old visible title was)
  T_<site>_Measure  transparent auto-height copies for the flowing grouplists (one per tier, so the
                    lines under the title follow the tier actually shown); not every site needs it
Fraunces in Kodi: line pitch = size x 1.233 x linespacing (Font.xml); a visible tier is drawn
(lines - 1) x pitch + 1.5 x size tall so the last line's descenders survive.

Usage: python skins/skin.daylight/_src/make_titles.py
"""
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "1080i" / "Includes_Titles.xml"
NATURAL = 1.233
FONTS = {  # name: (size, linespacing)
    "display_72": (72, 0.99), "display_60": (60, 0.92), "display_52": (52, 0.91),
    "display_48": (48, 0.98), "display_40": (40, 1.0), "serif_34": (34, 1.0), "serif_30": (30, 1.03),
}
# site: (width, [(font, lines)], first probe id, label kind)  label kind "textbox" or "label" (OSD)
SITES = {
    "VidInfo": (700, [("display_60", 2), ("display_48", 2), ("display_40", 3)], 7701),
    "MusInfo": (660, [("display_60", 2), ("display_48", 2), ("display_40", 3)], 7711),
    "NowPlaying": (1016, [("display_72", 2), ("display_60", 2), ("display_48", 3)], 7721),
    "HomeHero": (620, [("display_52", 2), ("display_40", 2), ("serif_30", 3)], 7731),
    "VidView": (500, [("display_60", 2), ("display_48", 2), ("display_40", 3)], 7741),
    "MusicView": (500, [("display_48", 2), ("display_40", 3)], 7751),
    "Generic": (500, [("display_48", 2), ("display_40", 2), ("serif_30", 3)], 7761),
    "OSD": (900, [("display_48", 1), ("display_40", 1)], 7771),
}


def pitch(font):
    size, ls = FONTS[font]
    return size * NATURAL * ls


def tier_conditions(n, base):
    out = []
    for i in range(n):
        c = [f"Integer.IsGreater(Container({base + j}).NumPages,1)" for j in range(i)]
        if i < n - 1:
            c.append(f"!Integer.IsGreater(Container({base + i}).NumPages,1)")
        out.append(" + ".join(c) or "true")
    return out


def site(name, width, tiers, base):
    conds = tier_conditions(len(tiers), base)
    T = "\t"
    L = [f"\t<!-- {name}: {', '.join(f'{f} x{n}' for f, n in tiers)} at {width} px (probes {base}-{base + len(tiers) - 2}) -->",
         f'\t<include name="T_{name}_Title">',
         '\t\t<param name="color">$VAR[DL_Ink]</param>',
         "\t\t<definition>"]
    for i, (font, lines) in enumerate(tiers[:-1]):
        L += [f'\t\t\t<control type="textbox" id="{base + i}">',
              "\t\t\t\t<left>0</left>", "\t\t\t\t<top>0</top>",
              f"\t\t\t\t<width>{width}</width>", f"\t\t\t\t<height>{round(pitch(font) * (lines + 0.5))}</height>",
              f"\t\t\t\t<font>{font}</font>", "\t\t\t\t<textcolor>00ffffff</textcolor>",
              "\t\t\t\t<label>$PARAM[label]</label>", "\t\t\t</control>"]
    for i, (font, lines) in enumerate(tiers):
        size = FONTS[font][0]
        h = round((lines - 1) * pitch(font) + 1.5 * size)
        kind = "label" if lines == 1 else "textbox"
        L += [f'\t\t\t<control type="{kind}">', "\t\t\t\t<left>0</left>", "\t\t\t\t<top>0</top>",
              f"\t\t\t\t<width>{width}</width>", f"\t\t\t\t<height>{h}</height>",
              f"\t\t\t\t<font>{font}</font>", "\t\t\t\t<textcolor>$PARAM[color]</textcolor>",
              "\t\t\t\t<label>$PARAM[label]</label>", f"\t\t\t\t<visible>{conds[i]}</visible>", "\t\t\t</control>"]
    L += ["\t\t</definition>", "\t</include>"]
    L += [f'\t<include name="T_{name}_Measure">', "\t\t<definition>"]
    for i, (font, lines) in enumerate(tiers):
        L += ['\t\t\t<control type="textbox">', f"\t\t\t\t<width>{width}</width>",
              f'\t\t\t\t<height max="{round(pitch(font) * lines)}">auto</height>',
              f"\t\t\t\t<font>{font}</font>", "\t\t\t\t<textcolor>00ffffff</textcolor>",
              "\t\t\t\t<label>$PARAM[label]</label>", f"\t\t\t\t<visible>{conds[i]}</visible>", "\t\t\t</control>"]
    L += ["\t\t</definition>", "\t</include>"]
    return L


def main():
    L = ['<?xml version="1.0" encoding="UTF-8"?>',
         "<!-- GENERATED by _src/make_titles.py - do not edit. Fitted Fraunces titles (see the script). -->",
         "<includes>"]
    for name, (width, tiers, base) in SITES.items():
        L += site(name, width, tiers, base)
    L.append("</includes>")
    OUT.write_text("\n".join(L) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
